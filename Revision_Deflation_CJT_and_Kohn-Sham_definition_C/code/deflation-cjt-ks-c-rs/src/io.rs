//! Output of data files.
//!
//! Every data file of Revision_Deflation_CJT_and_Kohn-Sham_definition_C begins with header lines that state the
//! program, the command that wrote the file, the content and the meaning of the
//! columns, so that a file can be understood without the documents.
//! The files are written to the folder `data/` below the current directory (or to the
//! folder named by the environment variable SPT_DATA_DIR).

use spacetimes::verify::Report;
use std::fs::{create_dir_all, File};
use std::io::{BufWriter, Write};
use std::path::PathBuf;

/// The first header line of every file.
pub fn generator_line() -> String {
    format!("generated by: deflation_cjt_ks_c (Rust crate spacetimes-deflation-cjt-ks-c, version {}; PROJECT spacetimes, Revision_Deflation_CJT_and_Kohn-Sham_definition_C)", env!("CARGO_PKG_VERSION"))
}

/// The folder for data files; it is created if it does not exist.
pub fn data_dir() -> PathBuf {
    let d = std::env::var("SPT_DATA_DIR").unwrap_or_else(|_| "data".to_string());
    let p = PathBuf::from(d);
    let _ = create_dir_all(&p);
    p
}

/// Write a CSV file of numbers: header lines "# key: value", a row of column names,
/// then one row per record, numbers with eleven significant digits.
pub fn write_csv(name: &str, meta: &[(&str, String)], header: &[&str], rows: &[Vec<f64>]) -> std::io::Result<PathBuf> {
    let cells: Vec<Vec<String>> = rows.iter().map(|r| r.iter().map(|x| format!("{:.10e}", x)).collect()).collect();
    write_csv_str(name, meta, header, &cells)
}

/// Write a CSV file whose cells are already formatted strings.
pub fn write_csv_str(name: &str, meta: &[(&str, String)], header: &[&str], rows: &[Vec<String>]) -> std::io::Result<PathBuf> {
    let path = data_dir().join(name);
    let mut w = BufWriter::new(File::create(&path)?);
    writeln!(w, "# {}", generator_line())?;
    for (k, v) in meta {
        writeln!(w, "# {}: {}", k, v)?;
    }
    writeln!(w, "{}", header.join(","))?;
    for r in rows {
        let cells: Vec<String> = r.iter().map(|c| if c.contains(',') || c.contains('"') { format!("\"{}\"", c.replace('"', "\"\"")) } else { c.clone() }).collect();
        writeln!(w, "{}", cells.join(","))?;
    }
    w.flush()?;
    Ok(path)
}

/// Write a list of checks as a text file (one line per check) and as a CSV file.
pub fn write_report(rep: &Report, txt_name: &str, csv_name: &str, title: &str, command: &str) -> std::io::Result<()> {
    let (ok, n) = rep.count();
    let mut w = BufWriter::new(File::create(data_dir().join(txt_name))?);
    writeln!(w, "{}", title)?;
    writeln!(w, "{}; command: {}", generator_line(), command)?;
    writeln!(w, "{} of {} checks passed", ok, n)?;
    writeln!(w)?;
    for c in &rep.checks {
        writeln!(w, "[{}] {}  ({}) {}", if c.pass { "PASS" } else { "FAIL" }, c.id, c.kind, c.statement)?;
    }
    w.flush()?;
    let rows: Vec<Vec<String>> = rep.checks.iter().map(|c| vec![c.id.clone(), c.kind.to_string(), if c.pass { "PASS".to_string() } else { "FAIL".to_string() }, c.statement.clone()]).collect();
    write_csv_str(csv_name, &[("content", title.to_string()), ("command", command.to_string())], &["id", "kind", "result", "statement"], &rows)?;
    Ok(())
}
