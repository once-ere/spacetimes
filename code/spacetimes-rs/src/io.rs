//! Output helpers: CSV files with '#'-prefixed metadata headers, and a tiny
//! scoped-thread parallel map (std only).

use std::fs::{create_dir_all, File};
use std::io::{BufWriter, Write};
use std::path::{Path, PathBuf};

/// Directory where all data files are written (relative to the working
/// directory; overridable with the SPT_DATA_DIR environment variable; [spacetimes] renamed from NCSS_DATA_DIR).
pub fn data_dir() -> PathBuf {
    let d = std::env::var("SPT_DATA_DIR").unwrap_or_else(|_| "data".to_string());
    let p = PathBuf::from(d);
    let _ = create_dir_all(&p);
    p
}

/// Write a CSV file: metadata lines (written as "# key: value"), a header row
/// and numeric rows.  Non-finite numbers are written as "nan"/"inf".
pub fn write_csv(name: &str, meta: &[(&str, String)], header: &[&str], rows: &[Vec<f64>]) -> std::io::Result<PathBuf> {
    let path = data_dir().join(name);
    let f = File::create(&path)?;
    let mut w = BufWriter::new(f);
    writeln!(w, "# generated by: spacetimes (Rust crate, version {})", env!("CARGO_PKG_VERSION"))?;
    for (k, v) in meta {
        writeln!(w, "# {}: {}", k, v)?;
    }
    writeln!(w, "{}", header.join(","))?;
    for r in rows {
        let s: Vec<String> = r.iter().map(|x| format!("{:.10e}", x)).collect();
        writeln!(w, "{}", s.join(","))?;
    }
    w.flush()?;
    Ok(path)
}

/// Write a CSV file whose cells are arbitrary strings (already formatted).
pub fn write_csv_str(name: &str, meta: &[(&str, String)], header: &[&str], rows: &[Vec<String>]) -> std::io::Result<PathBuf> {
    let path = data_dir().join(name);
    let f = File::create(&path)?;
    let mut w = BufWriter::new(f);
    writeln!(w, "# generated by: spacetimes (Rust crate, version {})", env!("CARGO_PKG_VERSION"))?;
    for (k, v) in meta {
        writeln!(w, "# {}: {}", k, v)?;
    }
    writeln!(w, "{}", header.join(","))?;
    for r in rows {
        let cells: Vec<String> = r
            .iter()
            .map(|c| if c.contains(',') || c.contains('"') { format!("\"{}\"", c.replace('"', "\"\"")) } else { c.clone() })
            .collect();
        writeln!(w, "{}", cells.join(","))?;
    }
    w.flush()?;
    Ok(path)
}

/// Does a file exist?
pub fn exists(p: &Path) -> bool {
    p.exists()
}

/// Parallel map over a slice using std::thread::scope and a shared atomic
/// work counter (dynamic load balancing: items of very different cost are
/// spread evenly over the threads).  The output order equals the input order.
pub fn par_map<T: Sync, R: Send, F: Fn(&T) -> R + Sync>(items: &[T], f: F) -> Vec<R> {
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::Mutex;
    let nthreads = std::thread::available_parallelism().map(|n| n.get()).unwrap_or(1).max(1);
    if nthreads == 1 || items.len() < 2 {
        return items.iter().map(&f).collect();
    }
    let next = AtomicUsize::new(0);
    let results: Mutex<Vec<(usize, R)>> = Mutex::new(Vec::with_capacity(items.len()));
    std::thread::scope(|s| {
        for _ in 0..nthreads.min(items.len()) {
            s.spawn(|| loop {
                let i = next.fetch_add(1, Ordering::Relaxed);
                if i >= items.len() {
                    break;
                }
                let r = f(&items[i]);
                results.lock().unwrap().push((i, r));
            });
        }
    });
    let mut v = results.into_inner().unwrap();
    v.sort_by_key(|p| p.0);
    v.into_iter().map(|p| p.1).collect()
}
