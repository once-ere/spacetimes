//! Command-line driver of the `spacetimes` crate.
//!
//! Run from the repository root:
//!
//! ```text
//! cargo run --release --manifest-path code/spacetimes-rs/Cargo.toml -- matrices
//! ```
//!
//! `matrices`  builds the two sets of Dirac matrices, runs every check (matrices,
//!             Dirac equations, fermion pairs), and writes data/gamma1644.txt,
//!             data/gamma1671.txt, data/matrix_checks.{txt,csv},
//!             data/pair_classification.{csv,txt} and provenance/generated/matrices.md.

use spacetimes::export::{latex_gmat, latex_imat, write_matrices, write_report, Fragments};
use spacetimes::gamma::{swap04, ETA1644, ETA1671};
use spacetimes::imat::{GMat, IMat};
use spacetimes::verify;

fn cmd_matrices() -> std::io::Result<bool> {
    let nb44 = "data/notebook_matrices_4+4.txt";
    let nb71 = "data/notebook_matrices_7+1.txt";
    let (gm, mut rep) = verify::run_all(nb44, nb71);
    // the two Dirac equations, and the classification of fermion pairs
    spacetimes::dirac::verify_dirac_44(&gm, &mut rep);
    spacetimes::dirac::verify_dirac_71(&gm, &mut rep);
    let pair_lines = spacetimes::pairs::run(&gm, &mut rep)?;
    std::fs::write("data/pair_classification.txt", pair_lines.join("\n") + "\n")?;
    let id16 = IMat::identity(16);

    // ---------------- plain-text matrix files ---------------------------------------
    // Names: the PROJECT symbols of the MASTER provenance (tag 1644 = 4+4, tag 1671 = 7+1).
    let refs: Vec<&IMat> = gm.gamma1671.iter().collect();
    let om1671 = IMat::product(&refs);
    let pl1644 = IMat { n: 16, m: 16, a: id16.sub(&gm.t16_8).a.iter().map(|x| x / 2).collect() };
    let pr1644 = IMat { n: 16, m: 16, a: id16.add(&gm.t16_8).a.iter().map(|x| x / 2).collect() };
    let mut m1644: Vec<(String, IMat)> = (0..8).map(|a| (format!("gamma1644[{}]", a), gm.gamma1644[a].clone())).collect();
    m1644.push(("omega1644".into(), gm.t16_8.clone()));
    m1644.push(("PL1644".into(), pl1644.clone()));
    m1644.push(("PR1644".into(), pr1644.clone()));
    m1644.push(("Cm1644".into(), gm.sigma16.clone()));
    m1644.push(("Cp1644".into(), gm.s44.clone()));
    m1644.push(("sigma88".into(), gm.sigma.clone()));
    for a in 0..8 {
        m1644.push((format!("tau1644[{}]", a), gm.tau[a].clone()));
    }
    for a in 0..8 {
        m1644.push((format!("taubar1644[{}]", a), gm.taubar[a].clone()));
    }
    write_matrices("data/gamma1644.txt", &[
        "PROJECT spacetimes: real 16x16 Dirac matrices of the 4+4 spacetime, gamma1644[A] = T16[A] of 4+4.nb (A = 0..7)".to_string(),
        format!("gamma1644[A].gamma1644[B] + gamma1644[B].gamma1644[A] = 2 eta1644[A][B], eta1644 = diag{:?} (= eta4488 of 4+4.nb)", ETA1644),
        "coordinates x0..x7: x0 hidden space, x1 x2 x3 space, x4 time, x5 x6 x7 extra times".to_string(),
        "omega1644 = gamma1644[0]...gamma1644[7] (= T16[8]); PL1644 = (1 - omega1644)/2, PR1644 = (1 + omega1644)/2 (= P_L, P_R of 4+4.nb)".to_string(),
        "Cm1644 = gamma1644[0..3] product (= sigma16 of 4+4.nb); Cp1644 = gamma1644[4..7] product (= S44 of 7+1.nb); sigma88 = sigma of 4+4.nb".to_string(),
        "tau1644[A] = tau[A], taubar1644[A] = taubar[A] of 4+4.nb: gamma1644[A] = [[0, taubar1644[A]], [tau1644[A], 0]]".to_string(),
        "generated by: spacetimes matrices".to_string()], &m1644)?;
    let two_pl1671 = GMat::from_real(&id16).sub(&GMat::i_times(&om1671));
    let two_pr1671 = GMat::from_real(&id16).add(&GMat::i_times(&om1671));
    let mut m1671: Vec<(String, IMat)> = (0..8).map(|a| (format!("gamma1671[{}]", a), gm.gamma1671[a].clone())).collect();
    m1671.push(("omega1671".into(), om1671.clone()));
    m1671.push(("Re(2 PL1671)".into(), two_pl1671.re.clone()));
    m1671.push(("Im(2 PL1671)".into(), two_pl1671.im.clone()));
    m1671.push(("Re(2 PR1671)".into(), two_pr1671.re.clone()));
    m1671.push(("Im(2 PR1671)".into(), two_pr1671.im.clone()));
    m1671.push(("Cp1671".into(), gm.gamma1671[4].clone()));
    m1671.push(("Cm1671".into(), gm.gamma1671[4].mul(&om1671)));
    for a in 0..8 {
        m1671.push((format!("tau1671[{}]", a), gm.tau_o[swap04(a)].clone()));
    }
    write_matrices("data/gamma1671.txt", &[
        "PROJECT spacetimes: real 16x16 Dirac matrices of the 7+1 spacetime (contravariant), gamma1671[A] = Gamma17up[swap04(A)] of 7+1.nb, swap04 = (0 4)".to_string(),
        format!("gamma1671[A].gamma1671[B] + gamma1671[B].gamma1671[A] = 2 eta1671[A][B], eta1671 = diag{:?} (NOT eta71 of 7+1.nb)", ETA1671),
        "coordinates x0..x7: x4 time; x0 hidden space, x1 x2 x3 space, x5 x6 x7 extra space".to_string(),
        "omega1671 = gamma1671[0]...gamma1671[7] (= Gamma17[8] = omega17 of 7+1.nb); chi1671 = i omega1671 (= chi17); PL1671 = (1 - chi1671)/2, PR1671 = (1 + chi1671)/2 (= PL17, PR17)".to_string(),
        "Cp1671 = gamma1671[4]; Cm1671 = gamma1671[4].omega1671".to_string(),
        "tau1671[A] = tauO[swap04(A)] of 7+1.nb are the real 8x8 matrices of the chiral equations (tau1671[4] = tauO[0] = identity)".to_string(),
        "generated by: spacetimes matrices".to_string()], &m1671)?;

    // ---------------- LaTeX fragments for `dirac matrices.md` -------------------------
    let mut fr = Fragments::new();
    for a in 0..8 {
        fr.add_display(&format!("gamma1644_{}", a), &format!("\\gamma_{{1644}}^{{{}}}", a), latex_imat(&gm.gamma1644[a], 8));
        fr.add_display(&format!("gamma1671_{}", a), &format!("\\gamma_{{1671}}^{{{}}}", a), latex_imat(&gm.gamma1671[a], 8));
        fr.add_display(&format!("tau1644_{}", a), &format!("\\tau_{{1644}}^{{{}}}", a), latex_imat(&gm.tau[a], 4));
        fr.add_display(&format!("taubar1644_{}", a), &format!("\\bar\\tau_{{1644}}^{{{}}}", a), latex_imat(&gm.taubar[a], 4));
        fr.add_display(&format!("tau1671_{}", a), &format!("\\tau_{{1671}}^{{{}}}", a), latex_imat(&gm.tau_o[swap04(a)], 4));
    }
    fr.add_display("omega1644", "\\omega_{1644}", latex_imat(&gm.t16_8, 8));
    fr.add_display("pl1644", "P_{1644}^{L}", latex_imat(&pl1644, 8));
    fr.add_display("pr1644", "P_{1644}^{R}", latex_imat(&pr1644, 8));
    fr.add_display("cm1644", "C_{1644}^{-}", latex_imat(&gm.sigma16, 8));
    fr.add_display("cp1644", "C_{1644}^{+}", latex_imat(&gm.s44, 8));
    fr.add_display("sigma88", "\\sigma_{88}", latex_imat(&gm.sigma, 4));
    fr.add_display("omega1671", "\\omega_{1671}", latex_imat(&om1671, 8));
    fr.add_display("two_pl1671", "2\\,P_{1671}^{L}", latex_gmat(&two_pl1671, 8));
    fr.add_display("two_pr1671", "2\\,P_{1671}^{R}", latex_gmat(&two_pr1671, 8));
    fr.add_display("cp1671", "C_{1671}^{+}", latex_imat(&gm.gamma1671[4], 8));
    fr.add_display("cm1671", "C_{1671}^{-}", latex_imat(&gm.gamma1671[4].mul(&om1671), 8));
    // the pair-symmetry table: which matrices C.gamma[A1]...gamma[Ar] are antisymmetric
    let ((sm44, sp44), (sm71, sp71)) = {
        let mut dummy = verify::Report::new();
        verify::verify_pairs(&gm, &mut dummy)
    };
    let sign = |s: i64| if s > 0 { "symmetric" } else { "**antisymmetric**" };
    let binom = [1usize, 8, 28, 56, 70, 56, 28, 8, 1];
    let mut tab = String::from("| rank $r$ | number of matrices | $C_{1644}^{-}\\,\\gamma^{A_1}\\cdots\\gamma^{A_r}$ | $C_{1644}^{+}\\,\\gamma^{A_1}\\cdots\\gamma^{A_r}$ | $C_{1671}^{-}\\,\\gamma^{A_1}\\cdots\\gamma^{A_r}$ | $C_{1671}^{+}\\,\\gamma^{A_1}\\cdots\\gamma^{A_r}$ |\n|:--:|:--:|:--:|:--:|:--:|:--:|\n");
    for r in 0..9 {
        tab.push_str(&format!("| {} | {} | {} | {} | {} | {} |\n", r, binom[r], sign(sm44[r]), sign(sp44[r]), sign(sm71[r]), sign(sp71[r])));
    }
    fr.add("pair_symmetry_table", tab);
    let (ok, n) = rep.count();
    // the log gets one more line ("ALL") below
    fr.add("n_checks", format!("{}", n + 1));
    fr.add("n_checks_passed", format!("{}", if rep.all_pass() { ok + 1 } else { ok }));
    std::fs::create_dir_all("provenance/generated")?;
    fr.write("provenance/generated/matrices.md")?;

    // ---------------- report -------------------------------------------------------------
    // a final entry so that the log itself states the overall result
    let all = rep.all_pass();
    rep.add("ALL", "exact", "every check above passed", all);
    write_report(&rep, "data/matrix_checks.txt", "data/matrix_checks.csv",
        "PROJECT spacetimes: checks of the real 16x16 Dirac matrices (4+4: gamma1644[A] = T16[A] of 4+4.nb; 7+1: gamma1671[A] = Gamma17up[swap04(A)] of 7+1.nb, swap04 = (0 4)); identifiers 44-.. refer to the 4+4 set, 71-.. to the 7+1 set")?;
    for c in &rep.checks {
        println!("[{}] {:<6} ({}) {}", if c.pass { "PASS" } else { "FAIL" }, c.id, c.kind, c.statement);
    }
    let (ok, n) = rep.count();
    println!("\n{} of {} checks passed", ok, n);
    Ok(rep.all_pass())
}

/// `channels`: the exchange amplitude of the Vorton-Scalar in every representative pair
/// channel, for both signatures; writes data/pair_channel_kernel.csv.
fn cmd_channels() -> std::io::Result<bool> {
    use spacetimes::kernel::{channel_table, f_pseudo_hidden, f_scalar_hidden, OneParticle};
    let gm = spacetimes::gamma::Gammas::build();
    // kinematics: fermion mass m = 1, momentum k on a sphere, 0 <= theta <= pi
    let m = 1.0;
    let thetas: Vec<f64> = (0..=12).map(|i| std::f64::consts::PI * i as f64 / 12.0).collect();
    let mut rows: Vec<Vec<String>> = Vec::new();
    let mut ok = true;
    for &k in &[0.1, 1.0, 3.0] {
        for op in [OneParticle::new_1671(&gm), OneParticle::new_1644(&gm)] {
            println!("\nsignature tag {}  (m = {}, |p| = |p'| = {}):  channel, norm of the two-particle content, F_S and F_P at theta = 0, 90, 180 degrees", op.tag, m, k);
            for r in channel_table(&op, m, k, &thetas) {
                println!("  {:<40} N = {:<8.4} F_S = {:+.4} {:+.4} {:+.4}   F_P = {:+.4} {:+.4} {:+.4}   {}",
                    r.channel, r.norm, r.f_s[0], r.f_s[6], r.f_s[12], r.f_p[0], r.f_p[6], r.f_p[12], r.description);
                for (i, th) in thetas.iter().enumerate() {
                    rows.push(vec![r.tag.to_string(), r.channel.clone(), r.description.clone(), format!("{}", m), format!("{}", k),
                        format!("{:.6}", th.to_degrees()), format!("{:.6e}", r.norm), format!("{:.10e}", r.f_s[i]), format!("{:.10e}", r.f_p[i])]);
                }
                // the hidden-axis channel must reproduce the closed forms
                if r.channel.ends_with("[0]") && r.channel.starts_with("Cm") {
                    for (i, th) in thetas.iter().enumerate() {
                        ok &= (r.f_s[i] - f_scalar_hidden(m, k, k, th.cos())).abs() < 1e-9;
                        ok &= (r.f_p[i] - f_pseudo_hidden(m, k, k, th.cos())).abs() < 1e-9;
                    }
                }
            }
        }
    }
    spacetimes::io::write_csv_str("pair_channel_kernel.csv",
        &[("content", "on-shell exchange amplitude F_X(p', p) of the Vorton-Scalar in representative pair channels; F > 0 is attraction".to_string()),
          ("definition", "F_X = Tr[Phi_X(p')^T V1 conj(Phi_X(p)) V2^T]/sqrt(N(p') N(p)); V = U^dagger Gamma U; Gamma_S = beta (radial mode), Gamma_P = i beta chi (phase mode)".to_string()),
          ("kinematics", "momenta of equal magnitude k in the (x1, x2) plane, scattering angle theta; fermion mass m".to_string()),
          ("signature", "1671: 7+1 spacetime; 1644: 4+4 spacetime, fields independent of x5 x6 x7".to_string()),
          ("norm", "N = squared norm of the two-particle content of the pair operator; N = 0 means the operator contains no pair of two particles".to_string()),
          ("command", "spacetimes channels".to_string())],
        &["signature", "channel", "description", "m", "k", "theta_deg", "norm", "F_scalar", "F_pseudoscalar"], &rows)?;
    println!("\nclosed forms of the hidden-axis channel reproduced: {}", ok);
    Ok(ok)
}

/// `gap`: solutions of the gap equation of the hidden-axis singlet superfluid;
/// writes data/gap_scan.csv and data/gap_profile.csv.
fn cmd_gap() -> std::io::Result<bool> {
    use spacetimes::gap::{critical_temperature, fermi_grid, solve_gap, Pairing};
    let m = 1.0;
    let mut rows: Vec<Vec<f64>> = Vec::new();
    let mut prof: Vec<Vec<f64>> = Vec::new();
    let mut ok = true;
    // couplings g = m/v_VS, radial masses m_s/m, Fermi momenta k_F/m
    let gs = [1.0, 2.0, 3.0];
    let mss = [0.03, 0.1, 0.3, 1.0];
    let kfs = [0.03, 0.05, 0.1, 0.2, 0.35, 0.5, 0.75, 1.0, 1.5, 2.0];
    println!("gaps in units of the Fermi kinetic energy E_F; V = vector (hidden-axis) channel, T = two-form channel, S = radial mode only");
    println!("{:>4} {:>6} {:>6} | {:>8} {:>8} | {:>10} {:>10} {:>10} | {:>7} | regime", "g", "m_s/m", "k_F/m", "lambda_S", "lambda_P", "gap_V", "gap_T", "gap_S", "Tc/gapV");
    for &g in &gs {
        for &m_s in &mss {
            for &k_f in &kfs {
                let base = Pairing { m, g, m_s, m_ph: 0.0, scalar: true, phase: true, phase_sign: 1.0, k_f };
                let ef = base.mu() - m; // Fermi kinetic energy
                let grid = fermi_grid(k_f, 60.0 * m.max(k_f), 11, 8);
                let lam_s = Pairing { phase: false, ..base }.lambda();
                let lam_p = Pairing { scalar: false, ..base }.lambda();
                // vector channel (S + P), two-form channel (S - P), radial mode only (S)
                let variants = [Pairing { ..base }, Pairing { phase_sign: -1.0, ..base }, Pairing { phase: false, ..base }];
                let mut gaps = [0.0; 3];
                let mut tc_ratio = f64::NAN;
                for (iv, p) in variants.iter().enumerate() {
                    let lam = p.lambda();
                    // start from the weak-coupling estimate, or from E_F at strong coupling
                    let start = (2.0 * ef * (-1.0 / lam.max(1e-3)).exp()).max(1e-11 * ef).min(ef);
                    let sol = solve_gap(p, &grid, 0.0, start, 1e-9, 40000);
                    let gap = if sol.converged && sol.delta_f > 1e-7 * ef { sol.delta_f } else { 0.0 };
                    gaps[iv] = gap;
                    if iv == 0 && gap > 0.0 {
                        if let Some(tc) = critical_temperature(p, &grid, 1e-11 * ef, 5.0 * (ef + m)) {
                            tc_ratio = tc / gap;
                        }
                        if (g, m_s, k_f) == (2.0, 0.1, 0.5) {
                            for (k, d) in sol.k.iter().zip(&sol.delta) {
                                prof.push(vec![*k, *d, *d / gap]);
                            }
                        }
                    }
                }
                // The chemical potential is kept at its weak-coupling value, which is
                // justified only while the gap is small compared with E_F (BCS regime).
                let bcs = gaps[0] < 0.3 * ef;
                println!("{:>4} {:>6} {:>6} | {:>8.4} {:>8.4} | {:>10.3e} {:>10.3e} {:>10.3e} | {:>7.4} | {}", g, m_s, k_f, lam_s, lam_p,
                    gaps[0] / ef, gaps[1] / ef, gaps[2] / ef, tc_ratio, if bcs { "BCS" } else { "beyond BCS (not quantitative)" });
                // sanity: T_c/gap must be close to the BCS value 0.567 whenever the gap is small
                if gaps[0] > 0.0 && gaps[0] < 0.05 * ef && tc_ratio.is_finite() {
                    ok &= (tc_ratio - 0.567).abs() < 0.03;
                }
                // sanity: the phase mode favours the vector channel
                ok &= gaps[0] >= gaps[2] && gaps[2] >= gaps[1];
                rows.push(vec![g, m_s, k_f, ef, lam_s, lam_p, gaps[0] / ef, gaps[1] / ef, gaps[2] / ef, tc_ratio, if bcs { 1.0 } else { 0.0 }]);
            }
        }
    }
    spacetimes::io::write_csv("gap_scan.csv",
        &[("content", "zero-temperature gap at the Fermi surface, and critical temperature, for the vector (hidden-axis) pair channel and for a two-form pair channel".to_string()),
          ("model", "exchange of the radial mode (mass m_s, scalar vertex) and of the massless phase mode (pseudoscalar vertex) of the Vorton-Scalar, both with coupling g = m/v_VS; kernels of kernel.rs; chemical potential fixed at sqrt(m^2 + k_F^2)".to_string()),
          ("units", "hbar = c = k_B = 1; momenta and masses in units of the fermion mass m; gaps in units of the Fermi kinetic energy E_F = sqrt(m^2 + k_F^2) - m".to_string()),
          ("columns", "lambda = N(0) W(k_F, k_F), N(0) = k_F sqrt(m^2+k_F^2)/(2 pi^2), for the radial mode (S) and the phase mode (P); gap_V: vector channel (kernel S + P); gap_T: two-form channel (kernel S - P); gap_S: radial mode only; gap = 0 means below the resolution 1e-7 E_F of the calculation; bcs_regime = 1 if gap_V < 0.3 E_F (only then is the fixed chemical potential justified)".to_string()),
          ("command", "spacetimes gap".to_string())],
        &["g", "m_s_over_m", "kF_over_m", "EF_over_m", "lambda_S", "lambda_P", "gap_V_over_EF", "gap_T_over_EF", "gap_S_over_EF", "Tc_over_gap_V", "bcs_regime"], &rows)?;
    spacetimes::io::write_csv("gap_profile.csv",
        &[("content", "momentum dependence of the gap function Delta(k) of the vector channel for g = 2, m_s = 0.1 m, k_F = 0.5 m".to_string()),
          ("command", "spacetimes gap".to_string())],
        &["k_over_m", "gap_over_m", "gap_over_gapF"], &prof)?;
    println!("\nchecks (T_c/gap = 0.567 at weak coupling; gap_V >= gap_S >= gap_T): {}", ok);
    Ok(ok)
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let cmd = args.get(1).map(|s| s.as_str()).unwrap_or("help");
    let ok = match cmd {
        "matrices" => cmd_matrices().expect("i/o error"),
        "channels" => cmd_channels().expect("i/o error"),
        "gap" => cmd_gap().expect("i/o error"),
        _ => {
            println!("usage: spacetimes <command>\n\ncommands:\n  matrices   build and verify the two sets of real 16x16 Dirac matrices; write data/ and provenance/generated/\n  channels   exchange amplitudes of the Vorton-Scalar in the pair channels; write data/pair_channel_kernel.csv\n  gap        gap equation of the hidden-axis singlet superfluid; write data/gap_scan.csv, data/gap_profile.csv");
            true
        }
    };
    if !ok {
        std::process::exit(1);
    }
}
