//! Command-line driver of the `spacetimes` crate.
//!
//! Run from the repository root:
//!
//! ```text
//! cargo run --release --manifest-path code/spacetimes-rs/Cargo.toml -- matrices
//! ```
//!
//! `matrices`  builds the two sets of Dirac matrices, runs every check, and writes
//!             data/gamma44.txt, data/gamma71.txt, data/matrix_checks.{txt,csv} and
//!             provenance/generated/matrices.md.

use spacetimes::export::{latex_gmat, latex_imat, write_matrices, write_report, Fragments};
use spacetimes::gamma::{pi71, ETA44, ETA71};
use spacetimes::imat::{GMat, IMat};
use spacetimes::verify;

fn cmd_matrices() -> std::io::Result<bool> {
    let nb44 = "data/notebook_matrices_4+4.txt";
    let nb71 = "data/notebook_matrices_7+1.txt";
    let (gm, mut rep) = verify::run_all(nb44, nb71);
    let id16 = IMat::identity(16);

    // ---------------- plain-text matrix files ---------------------------------------
    let refs: Vec<&IMat> = gm.g71.iter().collect();
    let om71 = IMat::product(&refs);
    let pl44 = IMat { n: 16, m: 16, a: id16.sub(&gm.t16_8).a.iter().map(|x| x / 2).collect() };
    let pr44 = IMat { n: 16, m: 16, a: id16.add(&gm.t16_8).a.iter().map(|x| x / 2).collect() };
    let mut m44: Vec<(String, IMat)> = (0..8).map(|a| (format!("gamma44[{}]", a), gm.g44[a].clone())).collect();
    m44.push(("omega44".into(), gm.t16_8.clone()));
    m44.push(("P_L44".into(), pl44.clone()));
    m44.push(("P_R44".into(), pr44.clone()));
    m44.push(("Cminus44=sigma16".into(), gm.sigma16.clone()));
    m44.push(("Cplus44=S44".into(), gm.s44.clone()));
    m44.push(("sigma".into(), gm.sigma.clone()));
    for a in 0..8 {
        m44.push((format!("tau[{}]", a), gm.tau[a].clone()));
    }
    for a in 0..8 {
        m44.push((format!("taubar[{}]", a), gm.taubar[a].clone()));
    }
    write_matrices("data/gamma44.txt", &[
        "PROJECT spacetimes: real 16x16 Dirac matrices of the 4+4 spacetime, gamma44[A] = T16[A] of 4+4.nb".to_string(),
        format!("gamma44[A].gamma44[B] + gamma44[B].gamma44[A] = 2 eta44[A][B], eta44 = diag{:?}", ETA44),
        "coordinates x0..x7: x0 hidden space, x1 x2 x3 space, x4 time, x5 x6 x7 extra times".to_string(),
        "generated by: spacetimes matrices".to_string()], &m44)?;
    let two_pl71 = GMat::from_real(&id16).sub(&GMat::i_times(&om71));
    let two_pr71 = GMat::from_real(&id16).add(&GMat::i_times(&om71));
    let mut m71: Vec<(String, IMat)> = (0..8).map(|a| (format!("gamma71[{}]", a), gm.g71[a].clone())).collect();
    m71.push(("omega71".into(), om71.clone()));
    m71.push(("Re(2P_L71)".into(), two_pl71.re.clone()));
    m71.push(("Im(2P_L71)".into(), two_pl71.im.clone()));
    m71.push(("Re(2P_R71)".into(), two_pr71.re.clone()));
    m71.push(("Im(2P_R71)".into(), two_pr71.im.clone()));
    m71.push(("Cplus71=gamma71[4]".into(), gm.g71[4].clone()));
    m71.push(("Cminus71=gamma71[4].omega71".into(), gm.g71[4].mul(&om71)));
    for a in 0..8 {
        m71.push((format!("rho[{}]=tauO[{}]", a, pi71(a)), gm.tau_o[pi71(a)].clone()));
    }
    write_matrices("data/gamma71.txt", &[
        "PROJECT spacetimes: real 16x16 Dirac matrices of the 7+1 spacetime (contravariant), gamma71[A] = Gamma17up[pi(A)] of 7+1.nb, pi = (0 4)".to_string(),
        format!("gamma71[A].gamma71[B] + gamma71[B].gamma71[A] = 2 eta71[A][B], eta71 = diag{:?}", ETA71),
        "coordinates x0..x7: x4 time; x0 hidden space, x1 x2 x3 space, x5 x6 x7 extra space".to_string(),
        "rho[A] = tauO[pi(A)] are the real 8x8 matrices of the chiral equations (rho[4] = tauO[0] = identity)".to_string(),
        "generated by: spacetimes matrices".to_string()], &m71)?;

    // ---------------- LaTeX fragments for `dirac matrices.md` -------------------------
    let mut fr = Fragments::new();
    for a in 0..8 {
        fr.add_display(&format!("g44_{}", a), &format!("\\gamma_{{(44)}}^{{{}}}", a), latex_imat(&gm.g44[a], 8));
        fr.add_display(&format!("g71_{}", a), &format!("\\gamma_{{(71)}}^{{{}}}", a), latex_imat(&gm.g71[a], 8));
        fr.add_display(&format!("tau_{}", a), &format!("\\tau^{{{}}}", a), latex_imat(&gm.tau[a], 4));
        fr.add_display(&format!("taubar_{}", a), &format!("\\bar\\tau^{{{}}}", a), latex_imat(&gm.taubar[a], 4));
        fr.add_display(&format!("rho_{}", a), &format!("\\rho^{{{}}}", a), latex_imat(&gm.tau_o[pi71(a)], 4));
    }
    fr.add_display("omega44", "\\omega_{(44)}", latex_imat(&gm.t16_8, 8));
    fr.add_display("pl44", "P_L^{(44)}", latex_imat(&pl44, 8));
    fr.add_display("pr44", "P_R^{(44)}", latex_imat(&pr44, 8));
    fr.add_display("cminus44", "C_-^{(44)}", latex_imat(&gm.sigma16, 8));
    fr.add_display("cplus44", "C_+^{(44)}", latex_imat(&gm.s44, 8));
    fr.add_display("sigma8", "\\sigma", latex_imat(&gm.sigma, 4));
    fr.add_display("omega71", "\\omega_{(71)}", latex_imat(&om71, 8));
    fr.add_display("two_pl71", "2\\,P_L^{(71)}", latex_gmat(&two_pl71, 8));
    fr.add_display("two_pr71", "2\\,P_R^{(71)}", latex_gmat(&two_pr71, 8));
    fr.add_display("cplus71", "C_+^{(71)}", latex_imat(&gm.g71[4], 8));
    fr.add_display("cminus71", "C_-^{(71)}", latex_imat(&gm.g71[4].mul(&om71), 8));
    // the pair-symmetry table (which C.Gamma^K are antisymmetric)
    let ((sm44, sp44), (sm71, sp71)) = {
        let mut dummy = verify::Report::new();
        verify::verify_pairs(&gm, &mut dummy)
    };
    let sign = |s: i64| if s > 0 { "S" } else { "A" };
    let binom = [1usize, 8, 28, 56, 70, 56, 28, 8, 1];
    let mut tab = String::from("| rank $r$ | number of matrices | $C_-^{(44)}\\Gamma^K$ | $C_+^{(44)}\\Gamma^K$ | $C_-^{(71)}\\Gamma^K$ | $C_+^{(71)}\\Gamma^K$ |\n|:--:|:--:|:--:|:--:|:--:|:--:|\n");
    for r in 0..9 {
        tab.push_str(&format!("| {} | {} | {} | {} | {} | {} |\n", r, binom[r], sign(sm44[r]), sign(sp44[r]), sign(sm71[r]), sign(sp71[r])));
    }
    fr.add("pair_symmetry_table", tab);
    let (ok, n) = rep.count();
    fr.add("n_checks", format!("{}", n));
    fr.add("n_checks_passed", format!("{}", ok));
    std::fs::create_dir_all("provenance/generated")?;
    fr.write("provenance/generated/matrices.md")?;

    // ---------------- report -------------------------------------------------------------
    // a final entry so that the log itself states the overall result
    let all = rep.all_pass();
    rep.add("ALL", "exact", "every check above passed", all);
    write_report(&rep, "data/matrix_checks.txt", "data/matrix_checks.csv",
        "PROJECT spacetimes: checks of the real 16x16 Dirac matrices (4+4: gamma44 = T16 of 4+4.nb; 7+1: gamma71[A] = Gamma17up[pi(A)] of 7+1.nb, pi = (0 4))")?;
    for c in &rep.checks {
        println!("[{}] {:<6} ({}) {}", if c.pass { "PASS" } else { "FAIL" }, c.id, c.kind, c.statement);
    }
    let (ok, n) = rep.count();
    println!("\n{} of {} checks passed", ok, n);
    Ok(rep.all_pass())
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let cmd = args.get(1).map(|s| s.as_str()).unwrap_or("help");
    let ok = match cmd {
        "matrices" => cmd_matrices().expect("i/o error"),
        _ => {
            println!("usage: spacetimes <command>\n\ncommands:\n  matrices   build and verify the two sets of real 16x16 Dirac matrices; write data/ and provenance/generated/");
            true
        }
    };
    if !ok {
        std::process::exit(1);
    }
}
