//! The command `spacetimes spinreps`: the spinor representation of Spin(4,4) and of Spin(7,1)
//! on the sixteen components, and its decomposition into two eight-dimensional parts
//! (provenance P12).
//!
//! THE QUESTION.  The author states two claims:
//!   (1) the 16x16 representation of Spin(4,4) is reducible to the direct sum of two 8x8
//!       irreducible representations, of "Spin(4,4)_left" and "Spin(4,4)_right";
//!   (2) the 16x16 representation of Spin(7,1) is reducible to the direct sum of 8x8
//!       irreducible representations, of "Spin(7,1)_left" and "Spin(7,1)_right".
//! This command decides, in exact integer arithmetic, what is true of the two claims for the
//! Dirac matrices of the project, and writes every check to data/spinrep_checks.txt.
//!
//! DEFINITIONS (the matrices come from the library, gamma.rs, which builds them from the
//! author's notebooks):
//!   gamma^A, A = 0..7: real 16x16 Dirac matrices, gamma^A gamma^B + gamma^B gamma^A = 2 eta^{AB},
//!       4+4: eta = diag(+1, +1, +1, +1, -1, -1, -1, -1);  7+1: eta = diag(-1, -1, -1, -1, +1, -1, -1, -1);
//!   Sigma^{AB} = (1/4)[gamma^A, gamma^B], A < B: the 28 generators of the Lie algebra so(4,4) or
//!       so(7,1) in the spinor representation; the group generated by the real exponentials of
//!       their linear combinations is Spin_0, the identity component of the spin group.  The
//!       program works with the integer matrices M^{AB} = 4 Sigma^{AB} = [gamma^A, gamma^B];
//!   omega = gamma^0 gamma^1 ... gamma^7;  chi = omega (4+4), chi = i omega (7+1);
//!   P^L = (1 - chi)/2, P^R = (1 + chi)/2;
//!   C^- = gamma^0 gamma^1 gamma^2 gamma^3 (4+4), C^- = gamma^4 omega (7+1).
//!
//! THE METHOD.  The Lie algebras so(4,4) and so(7,1) are semisimple, so every finite-dimensional
//! representation of them, and of the connected group Spin_0, is completely reducible (theorem
//! of Weyl): every invariant subspace has an invariant complement.  The invariant subspaces are
//! then described by the COMMUTANT, the set of matrices X with X M^{AB} = M^{AB} X for all A < B:
//!   * over the complex numbers, the dimension of the commutant is the sum of the squares of the
//!     multiplicities of the irreducible parts (Schur's lemma).  Dimension 2, with two non-zero
//!     invariant subspaces, means exactly two irreducible parts that are not equivalent;
//!   * over the real numbers, the representation is irreducible exactly when the real commutant
//!     contains no projector (idempotent) other than 0 and 1.
//! The commutant is the solution space of a homogeneous linear system with integer coefficients.
//! Its rank is computed modulo a prime (imat::rank), which is a lower bound for the rank over the
//! rationals; the program exhibits as many independent solutions as that bound leaves room for,
//! which proves the dimension exactly.  Because the coefficients are real, the complex commutant
//! has the same dimension as the real one.
//!
//! OUTPUT (data/): spinrep_checks.txt (every check with its statement and verdict),
//! spinrep_summary.csv (one row per spacetime).
//!
//! Run from the root of the repository:  cargo run --release --manifest-path code/spacetimes-rs/Cargo.toml -- spinreps

use spacetimes::gamma::Gammas;
use spacetimes::imat::{rank, GMat, IMat};
use spacetimes::io::{data_dir, write_csv_str};
use std::fs;

struct Report {
    lines: Vec<String>,
    passed: usize,
    total: usize,
}

impl Report {
    fn check(&mut self, id: &str, ok: bool, statement: String) {
        self.total += 1;
        if ok {
            self.passed += 1;
        }
        self.lines.push(format!("[{}] {}  {}", if ok { "PASS" } else { "FAIL" }, id, statement));
    }
}

fn identity() -> IMat {
    IMat::identity(16)
}

/// The rows of the integer linear system whose solutions X (16x16, flattened row by row) are the
/// matrices that commute with every matrix in `gens`: the entries of X G - G X.
fn commutant_rows(gens: &[IMat]) -> Vec<Vec<i64>> {
    let n = 16;
    let mut rows = Vec::new();
    for g in gens {
        for i in 0..n {
            for j in 0..n {
                // (X G - G X)_{ij} = sum_k X_{ik} G_{kj} - sum_k G_{ik} X_{kj}
                let mut row = vec![0i64; n * n];
                for k in 0..n {
                    row[i * n + k] += g.get(k, j);
                    row[k * n + j] -= g.get(i, k);
                }
                if row.iter().any(|&x| x != 0) {
                    rows.push(row);
                }
            }
        }
    }
    rows
}

fn commutes(a: &IMat, b: &IMat) -> bool {
    a.mul(b).sub(&b.mul(a)).is_zero()
}

fn anticommutes(a: &IMat, b: &IMat) -> bool {
    a.mul(b).add(&b.mul(a)).is_zero()
}

pub fn run() -> std::io::Result<bool> {
    let gm = Gammas::build();
    let mut rep = Report { lines: Vec::new(), passed: 0, total: 0 };
    let mut summary: Vec<Vec<String>> = Vec::new();

    for four_four in [true, false] {
        let (name, tag) = if four_four { ("4+4", "44") } else { ("7+1", "71") };
        let g: Vec<IMat> = if four_four { gm.gamma1644.clone() } else { gm.gamma1671.clone() };
        let eta: [i64; 8] = if four_four { [1, 1, 1, 1, -1, -1, -1, -1] } else { [-1, -1, -1, -1, 1, -1, -1, -1] };
        let one = identity();
        // the Clifford relations, as the basis of everything below
        let mut clifford = true;
        for a in 0..8 {
            for b in 0..8 {
                let lhs = g[a].mul(&g[b]).add(&g[b].mul(&g[a]));
                let rhs = if a == b { one.scale(2 * eta[a]) } else { IMat::zeros(16, 16) };
                clifford &= lhs.sub(&rhs).is_zero();
            }
        }
        rep.check(&format!("{}-R0", tag), clifford,
            format!("{}: the sixteen real matrices gamma^A satisfy gamma^A gamma^B + gamma^B gamma^A = 2 eta^{{AB}} with eta = diag({})", name,
                eta.iter().map(|x| format!("{:+}", x)).collect::<Vec<_>>().join(", ")));
        let refs: Vec<&IMat> = g.iter().collect();
        let omega = IMat::product(&refs);
        let pairs: Vec<(usize, usize)> = (0..8).flat_map(|a| ((a + 1)..8).map(move |b| (a, b))).collect();
        let gens: Vec<IMat> = pairs.iter().map(|&(a, b)| g[a].mul(&g[b]).sub(&g[b].mul(&g[a]))).collect();

        // ---------------------------------------------------------------- R1: omega
        let sq = omega.mul(&omega);
        let sign = if four_four { 1 } else { -1 };
        let omega_ok = sq.sub(&one.scale(sign)).is_zero() && omega.trace() == 0 && g.iter().all(|x| anticommutes(&omega, x)) && gens.iter().all(|m| commutes(&omega, m));
        rep.check(&format!("{}-R1", tag), omega_ok,
            format!("{}: omega = gamma^0 ... gamma^7 is real, omega^2 = {}1, Tr omega = 0; omega anticommutes with every gamma^A and commutes with all 28 generators Sigma^{{AB}}, so that the eigenspaces of chi are invariant under Spin_0", name, if four_four { "+" } else { "-" }));

        // ---------------------------------------------------------------- R2: the commutant
        let rows = commutant_rows(&gens);
        let r = rank(&rows);
        let sol_one = commutes(&one, &gens[0]) && gens.iter().all(|m| commutes(&one, m));
        let sol_omega = gens.iter().all(|m| commutes(&omega, m));
        // 1 and omega are linearly independent (omega is not a multiple of 1: it has trace 0 and is not 0)
        let indep = !omega.is_zero() && omega.trace() == 0;
        let dim = 256 - r;
        rep.check(&format!("{}-R2", tag), r == 254 && sol_one && sol_omega && indep,
            format!("{}: the linear system X M^{{AB}} = M^{{AB}} X (all 28 generators; {} integer equations for the 256 entries of X) has rank {} modulo a prime, so its solutions form a space of dimension at most {}; 1 and omega are two independent solutions; hence the commutant is exactly the span of 1 and omega, of dimension 2, over the real numbers and (the equations being real) also over the complex numbers",
                name, rows.len(), r, dim));

        // ---------------------------------------------------------------- R3: the decomposition
        let one_minus = one.sub(&omega);
        let one_plus = one.add(&omega);
        if four_four {
            // 2P^L = 1 - omega, 2P^R = 1 + omega, real; each of trace 8
            let traces = one_minus.trace() == 16 && one_plus.trace() == 16; // Tr(1 -+ omega) = 16, i.e. Tr P = 8
            let idem = one_minus.mul(&one_minus).sub(&one_minus.scale(2)).is_zero() && one_plus.mul(&one_plus).sub(&one_plus.scale(2)).is_zero();
            rep.check("44-R3", traces && idem && r == 254,
                "4+4: P^L = (1 - omega)/2 and P^R = (1 + omega)/2 are REAL projectors of rank 8 that commute with every generator: the real 16-dimensional representation is the direct sum of two real 8-dimensional invariant subspaces, left (chi = -1) and right (chi = +1). The commutant is spanned by P^L and P^R (check R2): by Schur's lemma each part is irreducible over the complex numbers, and hence also over the real numbers, and the two parts are not equivalent (no non-zero invariant map from one to the other)".to_string());
            // the basis of the files is a chiral basis: the generators are block-diagonal
            let blockdiag = gens.iter().all(|m| m.block(0, 8, 8, 8).is_zero() && m.block(8, 0, 8, 8).is_zero());
            let diag_sign = omega.get(0, 0);
            let omega_diag = omega.sub(&IMat::diag(&(0..16).map(|i| if i < 8 { diag_sign } else { -diag_sign }).collect::<Vec<i64>>())).is_zero();
            rep.check("44-R4", blockdiag && omega_diag,
                format!("4+4: in the basis of the matrix files the generators are block-diagonal with two 8x8 blocks, and omega = diag({}1_8, {}1_8): the first eight components are the {} part and the last eight the {} part",
                    if diag_sign > 0 { "+" } else { "-" }, if diag_sign > 0 { "-" } else { "+" },
                    if diag_sign > 0 { "right-handed" } else { "left-handed" }, if diag_sign > 0 { "left-handed" } else { "right-handed" }));
        } else {
            // 7+1: omega^2 = -1, so span(1, omega) is a copy of the complex numbers: no real idempotent other than 0, 1
            rep.check("71-R3", r == 254 && sq.sub(&one.scale(-1)).is_zero(),
                "7+1: the real commutant is spanned by 1 and omega with omega^2 = -1, an algebra isomorphic to the complex numbers; (a + b omega)^2 = a + b omega has only the solutions 0 and 1, so the real commutant contains no projector other than 0 and 1, and the real 16-dimensional representation is IRREDUCIBLE over the real numbers. Over the complex numbers P^L = (1 - i omega)/2 and P^R = (1 + i omega)/2 split it into two 8-dimensional parts, which by check R2 are irreducible and not equivalent".to_string());
            let blockdiag = gens.iter().all(|m| m.block(0, 8, 8, 8).is_zero() && m.block(8, 0, 8, 8).is_zero());
            rep.check("71-R4", !blockdiag,
                "7+1: in the basis of the matrix files the generators are not block-diagonal: no choice of real components separates the two chiral parts; the left part consists of complex combinations of the real components".to_string());
            // complex conjugation maps P^L onto P^R because omega is real
            let pl = GMat { re: one.scale(1), im: omega.neg() };
            let pr = GMat { re: one.scale(1), im: omega.clone() };
            let conj_pl = GMat { re: pl.re.clone(), im: pl.im.neg() };
            rep.check("71-R5", conj_pl.sub(&pr).is_zero(),
                "7+1: because omega is real, the complex conjugate of 2P^L = 1 - i omega is 2P^R = 1 + i omega, and the generators are real: complex conjugation maps the left part onto the right part and commutes with the action of Spin_0. The right part is the complex conjugate of the left part".to_string());
        }

        // ---------------------------------------------------------------- R6: faithful action of the Lie algebra on each part
        let faithful = |q: &IMat| -> usize {
            // over the complex numbers for 7+1 (P = (1 -+ i omega)/2), over the reals for 4+4
            if four_four {
                let rows: Vec<Vec<i64>> = gens.iter().map(|m| m.mul(q).flatten()).collect();
                rank(&rows)
            } else {
                // M (1 -+ i omega) = M -+ i M omega; complex rank via the realification [Re, Im] and [-Im, Re]
                let mut rows = Vec::new();
                for m in &gens {
                    let re = m.flatten();
                    let im: Vec<i64> = m.mul(q).flatten();
                    rows.push(re.iter().chain(im.iter()).cloned().collect::<Vec<i64>>());
                    rows.push(im.iter().map(|x| -x).chain(re.iter().cloned()).collect::<Vec<i64>>());
                }
                rank(&rows) / 2
            }
        };
        let (rl, rr) = if four_four { (faithful(&one_minus), faithful(&one_plus)) } else { (faithful(&omega.neg()), faithful(&omega)) };
        rep.check(&format!("{}-R6", tag), rl == 28 && rr == 28,
            format!("{}: the 28 generators remain linearly independent on each part (rank {} on the left part, {} on the right part): the whole Lie algebra so({}) acts faithfully on each 8-dimensional part; each part is a representation of the one group Spin_0({}), not of a subgroup", name, rl, rr, if four_four { "4,4" } else { "7,1" }, if four_four { "4,4" } else { "7,1" }));

        // ---------------------------------------------------------------- R7: the invariant bilinear form psi^T C^- psi'
        let cm = if four_four { IMat::product(&[&g[0], &g[1], &g[2], &g[3]]) } else { g[4].mul(&omega) };
        let invariant = gens.iter().all(|m| cm.mul(m).add(&m.transpose().mul(&cm)).is_zero());
        let cm_sym = cm.is_symmetric();
        let cm_anti = cm.is_antisymmetric();
        let cm_sq = cm.mul(&cm);
        if four_four {
            let comm = commutes(&cm, &omega);
            // signature of the form on each part: C^- squares to 1, so its eigenvalues are +-1; Tr(P C^-) gives the signature
            let tl = one_minus.mul(&cm).trace(); // = 2 Tr(P^L C^-)
            let tr = one_plus.mul(&cm).trace();
            rep.check("44-R7", invariant && cm_sym && comm && cm_sq.sub(&one).is_zero() && tl == 0 && tr == 0,
                format!("4+4: C^- is real and symmetric, (C^-)^2 = 1, C^- M^{{AB}} + (M^{{AB}})^T C^- = 0 for all generators, and C^- commutes with omega: the form psi^T C^- psi' is invariant and pairs each part with itself; on each part it has the eigenvalues +1 and -1 four times each (2 Tr(P^L C^-) = {}, 2 Tr(P^R C^-) = {}), so that each part carries an invariant symmetric form of signature (4,4), and the image of Spin_0(4,4) in each part lies in SO(4,4)", tl, tr));
        } else {
            let anti = anticommutes(&cm, &omega);
            rep.check("71-R7", invariant && anti && (cm_sym || cm_anti),
                format!("7+1: C^- M^{{AB}} + (M^{{AB}})^T C^- = 0 for all generators (C^- is {}), and C^- anticommutes with omega: the invariant form psi^T C^- psi' pairs the left part with the right part. The right part is therefore also the dual of the left part", if cm_sym { "symmetric" } else { "antisymmetric" }));
        }

        // ---------------------------------------------------------------- R8: central elements; kernels of the two parts
        let factors = [(0usize, 1usize), (2, 3), (4, 5), (6, 7)];
        let fsq: Vec<i64> = factors.iter().map(|&(a, b)| { let f = g[a].mul(&g[b]); let s = f.mul(&f); if s.sub(&one.scale(-1)).is_zero() { -1 } else if s.sub(&one).is_zero() { 1 } else { 0 } }).collect();
        let product_ok = IMat::product(&[&g[0].mul(&g[1]), &g[2].mul(&g[3]), &g[4].mul(&g[5]), &g[6].mul(&g[7])]).sub(&omega).is_zero();
        if four_four {
            rep.check("44-R8", product_ok && fsq.iter().all(|&x| x == -1),
                "4+4: omega = (gamma^0 gamma^1)(gamma^2 gamma^3)(gamma^4 gamma^5)(gamma^6 gamma^7), and each factor squares to -1, so that each factor equals exp((pi/2) gamma^a gamma^b) = exp(pi Sigma^{ab}): omega and -omega lie in Spin_0(4,4). omega acts as -1 on the left part and as +1 on the right part. Hence the element -omega acts as the identity on the left part and the element omega as the identity on the right part: NEITHER 8-dimensional part is a faithful representation of Spin_0(4,4); the 16-dimensional sum is".to_string());
        } else {
            rep.check("71-R8", product_ok && fsq == vec![-1, -1, 1, -1],
                "7+1: omega = (gamma^0 gamma^1)(gamma^2 gamma^3)(gamma^4 gamma^5)(gamma^6 gamma^7), where the factor with the time axis x4 squares to +1 (a boost) and the other three to -1. omega anticommutes with every gamma^A, so that it maps every vector to its negative; that reverses the direction of time, and therefore omega is not in Spin_0(7,1). The central elements of Spin_0(7,1) are +1 and -1, and -1 acts as -1 on each part: each 8-dimensional part is a faithful representation of Spin_0(7,1)".to_string());
        }

        summary.push(vec![
            name.to_string(),
            format!("{}", sign),
            format!("{}", dim),
            if four_four { "1" } else { "0" }.to_string(),
            "2".to_string(),
            "1".to_string(),
            format!("{}", if four_four { "real, self-dual, symmetric form of signature (4,4)" } else { "complex; right = complex conjugate of left = dual of left" }),
            format!("{}", if four_four { "no (kernels {1,-omega} and {1,omega})" } else { "yes" }),
        ]);
    }

    // ---------------------------------------------------------------- write
    let mut text = String::new();
    text.push_str("# PROJECT spacetimes: the spinor representation of Spin(4,4) and Spin(7,1) on sixteen components and its two eight-dimensional parts\n");
    text.push_str("# generated by: spacetimes spinreps (code/spacetimes-rs/src/spinrep_cmd.rs); exact integer arithmetic\n");
    text.push_str("# Sigma^{AB} = (1/4)[gamma^A, gamma^B]; omega = gamma^0...gamma^7; chi = omega (4+4), i omega (7+1); P^L = (1 - chi)/2, P^R = (1 + chi)/2\n");
    for l in &rep.lines {
        text.push_str(l);
        text.push('\n');
    }
    text.push_str(&format!("{} of {} checks passed\n", rep.passed, rep.total));
    fs::create_dir_all(data_dir())?;
    fs::write(data_dir().join("spinrep_checks.txt"), &text)?;
    write_csv_str("spinrep_summary.csv",
        &[("content", "the decomposition of the 16-dimensional spinor representation of Spin_0 into its chiral parts, for the two spacetimes".to_string()),
          ("columns", "spacetime; omega_squared: +1 or -1; commutant_dim: dimension of the real (and of the complex) commutant of the 28 generators; reducible_over_reals: 1 if the real representation splits into two real invariant subspaces; parts_over_complex: number of irreducible parts over the complex numbers; parts_inequivalent: 1 if they are not equivalent; parts: the nature of the parts; parts_faithful: whether each part is a faithful representation of Spin_0".to_string()),
          ("command", "spacetimes spinreps".to_string())],
        &["spacetime", "omega_squared", "commutant_dim", "reducible_over_reals", "parts_over_complex", "parts_inequivalent", "parts", "parts_faithful"], &summary)?;
    for l in &rep.lines {
        println!("{}", l);
    }
    println!("spinreps: {} of {} checks passed", rep.passed, rep.total);
    Ok(rep.passed == rep.total)
}
