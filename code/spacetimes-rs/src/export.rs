//! Writing matrices and check reports to files: plain text for other programs,
//! LaTeX arrays (inside Markdown) for the provenance documents.

use crate::imat::{GMat, IMat};
use crate::verify::Report;
use std::fmt::Write as FmtWrite;
use std::fs;
use std::io::Write;

/// Write named integer matrices to a plain text file:
///
/// ```text
/// MATRIX <name> rows <r> cols <c>
/// <r lines of c integers>
/// ```
pub fn write_matrices(path: &str, header: &[String], mats: &[(String, IMat)]) -> std::io::Result<()> {
    let mut f = fs::File::create(path)?;
    for h in header {
        writeln!(f, "# {}", h)?;
    }
    for (name, m) in mats {
        writeln!(f, "MATRIX {} rows {} cols {}", name, m.n, m.m)?;
        for i in 0..m.n {
            let row: Vec<String> = (0..m.m).map(|j| format!("{:2}", m.get(i, j))).collect();
            writeln!(f, "{}", row.join(" "))?;
        }
    }
    Ok(())
}

/// LaTeX source of a matrix as an array in parentheses.  Zeros are printed as a
/// centred dot so that the pattern of the non-zero entries is visible; if
/// `block` > 0, rules are drawn after every `block` rows and columns.
pub fn latex_array<F: Fn(usize, usize) -> String>(n: usize, m: usize, block: usize, entry: F) -> String {
    let mut cols = String::new();
    for j in 0..m {
        if block > 0 && j > 0 && j % block == 0 {
            cols.push('|');
        }
        cols.push('r');
    }
    let mut s = String::new();
    write!(s, "\\left(\\begin{{array}}{{{}}}\n", cols).unwrap();
    for i in 0..n {
        if block > 0 && i > 0 && i % block == 0 {
            s.push_str("\\hline\n");
        }
        let row: Vec<String> = (0..m).map(|j| entry(i, j)).collect();
        s.push_str(&row.join(" & "));
        // rows are set 1.8 pt closer than the default, so that three 16x16 matrices fit on a page
        s.push_str(if i + 1 < n { " \\\\[-1.8pt]\n" } else { "\n" });
    }
    s.push_str("\\end{array}\\right)");
    s
}

/// LaTeX array of an integer matrix (zeros as dots).  Every entry that has no minus
/// sign is preceded by an invisible one (`\phantom{-}`), so that all columns of a
/// matrix with entries 0, +1, -1 get the same width and the matrix is printed on a
/// regular grid.
pub fn latex_imat(m: &IMat, block: usize) -> String {
    latex_array(m.n, m.m, block, |i, j| {
        let x = m.get(i, j);
        if x == 0 {
            "\\phantom{-}\\cdot".to_string()
        } else if x > 0 {
            format!("\\phantom{{-}}{}", x)
        } else {
            format!("{}", x)
        }
    })
}

/// LaTeX array of a Gaussian-integer matrix (zeros as dots, entries a + b i).
pub fn latex_gmat(m: &GMat, block: usize) -> String {
    latex_array(m.re.n, m.re.m, block, |i, j| {
        let (a, b) = (m.re.get(i, j), m.im.get(i, j));
        match (a, b) {
            (0, 0) => "\\phantom{-}\\cdot".to_string(),
            (a, 0) if a > 0 => format!("\\phantom{{-}}{}", a),
            (a, 0) => format!("{}", a),
            (0, 1) => "\\phantom{-}i".to_string(),
            (0, -1) => "-i".to_string(),
            (0, b) => format!("{}i", b),
            (a, b) => format!("{}{:+}i", a, b),
        }
    })
}

/// A collection of named Markdown fragments, written as
/// `<!-- BEGIN name -->` ... `<!-- END name -->` blocks.  The script
/// `code/scripts/assemble_docs.py` inserts them into the document sources.
pub struct Fragments {
    pub items: Vec<(String, String)>,
}

impl Fragments {
    pub fn new() -> Fragments {
        Fragments { items: Vec::new() }
    }
    pub fn add(&mut self, name: &str, body: String) {
        self.items.push((name.to_string(), body));
    }
    /// A displayed equation `lhs = <matrix>`.
    pub fn add_display(&mut self, name: &str, lhs: &str, array: String) {
        self.add(name, format!("$$\n{} = {}\n$$", lhs, array));
    }
    pub fn write(&self, path: &str) -> std::io::Result<()> {
        let mut f = fs::File::create(path)?;
        writeln!(f, "<!-- GENERATED by `spacetimes` (code/spacetimes-rs); do not edit by hand -->")?;
        for (name, body) in &self.items {
            writeln!(f, "<!-- BEGIN {} -->\n{}\n<!-- END {} -->", name, body, name)?;
        }
        Ok(())
    }
}

/// The report as plain text (one line per check) and as CSV.
pub fn write_report(rep: &Report, txt_path: &str, csv_path: &str, title: &str) -> std::io::Result<()> {
    let mut t = fs::File::create(txt_path)?;
    let (ok, n) = rep.count();
    writeln!(t, "{}", title)?;
    writeln!(t, "{} of {} checks passed", ok, n)?;
    writeln!(t)?;
    for c in &rep.checks {
        writeln!(t, "[{}] {:<6} ({}) {}", if c.pass { "PASS" } else { "FAIL" }, c.id, c.kind, c.statement)?;
    }
    let mut f = fs::File::create(csv_path)?;
    writeln!(f, "# generated by: spacetimes (Rust crate, version {})", env!("CARGO_PKG_VERSION"))?;
    writeln!(f, "# {}", title)?;
    writeln!(f, "id,kind,result,statement")?;
    for c in &rep.checks {
        writeln!(f, "{},{},{},\"{}\"", c.id, c.kind, if c.pass { "PASS" } else { "FAIL" }, c.statement.replace('"', "'"))?;
    }
    Ok(())
}
