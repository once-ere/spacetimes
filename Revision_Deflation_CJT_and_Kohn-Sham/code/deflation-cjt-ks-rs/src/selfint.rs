//! The self-interaction of the 16-component Dirac field: the nine channels, in exact arithmetic.
//!
//! THE LAGRANGIAN.  The author's Dirac Lagrangian contains, beside the kinetic term and the
//! mass term, the self-interaction (his document KOHN_SHAM_GRAVITY, section 15.1)
//!
//!     L_self = -(1/2) sum_{r=0}^{8} g_r I_r ,
//!     I_r    = sum over the index sets K of r different indices of  (psibar Theta_K psi)(psibar Theta^K psi) ,
//!
//! with nine real coupling constants g_0 .. g_8 (dimension length^6 in eight dimensions).
//! An index set is K = {A_1 < A_2 < .. < A_r}, a subset of {0, .., 7}; there are
//! 1, 8, 28, 56, 70, 56, 28, 8, 1 of them for r = 0 .. 8, 256 in all.
//!
//! THE MATRICES Theta^K ("upper") and Theta_K ("lower").
//!
//!     Theta^K = phase_K  Gamma^{A_1} Gamma^{A_2} .. Gamma^{A_r} ,       phase_K = 1 or i ,
//!
//! where the phase is the one for which the bilinear psibar Theta^K psi is REAL, that is,
//! for which the matrix M_K = Adj Theta^K is Hermitian (psibar = psi^dagger Adj).
//!
//!     Theta_K = (Theta^K)^{-1} = eps_K Theta^K ,       eps_K = +1 or -1 ,   (Theta^K)^2 = eps_K 1 .
//!
//! On the 7+1 spacetime eps_K is the product eta_K of the squares of the Dirac matrices in
//! K, and Theta_K = eta_K Theta^K is the author's definition ("indices lowered with the
//! metric").  Defining the lower matrix as the INVERSE has the same content there and can
//! be used unchanged on the 4+4 spacetime, where the adjoint matrix is different.
//! With M_K the invariant is  I_r = sum_K eps_K (psi^dagger M_K psi)^2.
//!
//! THREE MODELS are treated by the same routines.
//!
//!   `S71`   7+1.  Gamma^A = gamma1671^A (real), Adj = gamma1671^4 (the Dirac adjoint
//!           psibar = psi^dagger gamma^4).  phase_K = i for r = 2, 3, 6, 7.
//!   `S44C`  4+4, covariant.  Gamma^A = gamma1644^A (real), Adj = C^- = gamma^0 gamma^1
//!           gamma^2 gamma^3 (psitilde = psi^dagger C^-), invariant under the whole group
//!           Spin(4,4).  phase_K = i for r = 1, 2, 5, 6;  eps_K = (-1)^r eta_K.
//!   `S44Q`  4+4, quantized sector.  The field does not depend on x5, x6, x7 and is
//!           quantized with the positive Lagrangian psi^dagger (i d_4 - h) psi.  The adjoint
//!           is psibar = psi^dagger beta with beta = -i gamma1644^4, and the matrices are
//!           Gamma_eff^A = -i gamma1644^A (A = 0..4), Gamma_eff^t = gamma1644^t (t = 5, 6, 7),
//!           whose squares are (-1,-1,-1,-1,+1,-1,-1,-1): the algebra of the 7+1 matrices.
//!           Every formula of `S71` holds; the symmetry of the interaction that is a symmetry
//!           of spacetime is Spin(4,1) x Spin(3).
//!
//! WHAT IS PROVED HERE (exactly, with Gaussian-integer matrices; see `verify_model`).
//!
//!   1. All 256 M_K are Hermitian; the 256 Theta^K are a basis of the 16x16 matrices,
//!      Tr(Theta_K Theta^L) = 16 delta_K^L.
//!   2. Every I_r is invariant under the 28 rotations and boosts generated by
//!      (1/2) Gamma^A Gamma^B.
//!   3. FIERZ REARRANGEMENT.  For all four spinor indices a, b, c, d
//!
//!          sum_{K of rank r} (Theta_K)_{ab} (Theta^K)_{cd} = sum_s F_rs sum_{L of rank s} (Theta_L)_{ad} (Theta^L)_{cb} ,
//!          F_rs = (1/16) sum_l (-1)^{rs - l} C(s, l) C(8 - s, r - l) ,        F^2 = 1 .
//!
//!   4. THEOREM.  For anticommuting (Grassmann) fields the nine invariants obey the five
//!      linear relations (1 + F) I = 0, and only four of them are independent.  With the
//!      choice I_0, I_1, I_7, I_8 (scalar, vector, axial vector, pseudoscalar):
//!
//!          I_2 = -3 I_0 - I_1 - I_7 - I_8 ,      I_3 = -4 I_0 - I_7 + 4 I_8 ,     I_4 = -5 I_0 - 5 I_8 ,
//!          I_5 = -4 I_0 - I_1 + 4 I_8 ,          I_6 = -I_0 + I_1 + I_7 - 3 I_8 .
//!
//!      Hence sum_r g_r I_r = g_0eff I_0 + g_1eff I_1 + g_7eff I_7 + g_8eff I_8 with
//!
//!          g_0eff = g_0 - 3 g_2 - 4 g_3 - 5 g_4 - 4 g_5 - g_6 ,     g_1eff = g_1 - g_2 - g_5 + g_6 ,
//!          g_7eff = g_7 - g_2 - g_3 + g_6 ,                         g_8eff = g_8 - g_2 + 4 g_3 - 5 g_4 + 4 g_5 - 3 g_6 .
//!
//!   5. HARTREE-FOCK.  For a state without pairing and with the one-body density matrix
//!      n_ab = <psi_b^dagger psi_a>, the expectation value of the normal-ordered interaction is
//!
//!          E_HF = (1/2) sum_r g_r sum_K eps_K [ Tr(M_K n)^2 - Tr(M_K n M_K n) ] ,
//!
//!      and the mean-field potential is U = sum_r g_r sum_K eps_K [ Tr(M_K n) M_K - M_K n M_K ].
//!      For uniform matter n = (rho 1 + rho_S beta)/16 (S71, S44Q):
//!          E_HF = (1/2) [ G_1 rho^2 + G_0 rho_S^2 ],   U = G_1 rho 1 + G_0 rho_S beta,   G = (1 - F^T) g .
//!      S44C: n = (rho 1 + rho_S beta + rho_W W + rho_SW W beta)/16 and
//!          E_HF = (1/2) [ G_V0 rho^2 + G_S0 rho_S^2 + G_1 rho_W^2 + G_0 rho_SW^2 ] .
//!   6. PAIRS.  With the pair density kappa_ab = <psi_a psi_b> (antisymmetric) the pairing
//!      energy is E_pair = (1/2) sum_r g_r Tr(kappa^dagger P_r(kappa)),  P_r(kappa) = sum_K eps_K M_K kappa M_K^T.
//!      For the pair matrices of two particles at rest, kappa = P_+ X P_+^T with
//!      X = C^- gamma^J antisymmetric and P_+ = (1 + beta)/2, kappa is an eigenvector of
//!      the projected map, and the pair coupling is G_pair = sum_r g_r q_r (attractive if negative).
//!   7. CHIRAL PHASE ROTATION psi -> exp(i theta chi) psi: which combinations of the couplings
//!      are invariant.
//!
//! All matrices have entries in {0, +1, -1, +i, -i}; the arithmetic is exact (integers).

use crate::rat::Rat;
use spacetimes::gamma::Gammas;
use spacetimes::imat::IMat;
use spacetimes::verify::Report;

const N: usize = 16;

/// A 16x16 matrix of Gaussian integers (re + i im), stored row by row.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct G16 {
    pub re: Vec<i64>,
    pub im: Vec<i64>,
}

impl G16 {
    pub fn zero() -> G16 {
        G16 { re: vec![0; N * N], im: vec![0; N * N] }
    }
    pub fn identity() -> G16 {
        let mut m = G16::zero();
        for i in 0..N {
            m.re[i * N + i] = 1;
        }
        m
    }
    /// A real integer matrix of the main project as a Gaussian-integer matrix.
    pub fn from_imat(m: &IMat) -> G16 {
        assert!(m.n == N && m.m == N);
        G16 { re: m.a.clone(), im: vec![0; N * N] }
    }
    /// i times the matrix.
    pub fn times_i(&self) -> G16 {
        G16 { re: self.im.iter().map(|x| -x).collect(), im: self.re.clone() }
    }
    /// -i times the matrix.
    pub fn times_minus_i(&self) -> G16 {
        G16 { re: self.im.clone(), im: self.re.iter().map(|x| -x).collect() }
    }
    pub fn mul(&self, b: &G16) -> G16 {
        let mut out = G16::zero();
        for i in 0..N {
            for k in 0..N {
                let (ar, ai) = (self.re[i * N + k], self.im[i * N + k]);
                if ar == 0 && ai == 0 {
                    continue;
                }
                for j in 0..N {
                    let (br, bi) = (b.re[k * N + j], b.im[k * N + j]);
                    if br == 0 && bi == 0 {
                        continue;
                    }
                    out.re[i * N + j] += ar * br - ai * bi;
                    out.im[i * N + j] += ar * bi + ai * br;
                }
            }
        }
        out
    }
    pub fn add(&self, b: &G16) -> G16 {
        G16 { re: self.re.iter().zip(&b.re).map(|(x, y)| x + y).collect(), im: self.im.iter().zip(&b.im).map(|(x, y)| x + y).collect() }
    }
    pub fn sub(&self, b: &G16) -> G16 {
        G16 { re: self.re.iter().zip(&b.re).map(|(x, y)| x - y).collect(), im: self.im.iter().zip(&b.im).map(|(x, y)| x - y).collect() }
    }
    pub fn scale(&self, c: i64) -> G16 {
        G16 { re: self.re.iter().map(|x| c * x).collect(), im: self.im.iter().map(|x| c * x).collect() }
    }
    pub fn neg(&self) -> G16 {
        self.scale(-1)
    }
    pub fn transpose(&self) -> G16 {
        let mut out = G16::zero();
        for i in 0..N {
            for j in 0..N {
                out.re[j * N + i] = self.re[i * N + j];
                out.im[j * N + i] = self.im[i * N + j];
            }
        }
        out
    }
    pub fn conj(&self) -> G16 {
        G16 { re: self.re.clone(), im: self.im.iter().map(|x| -x).collect() }
    }
    /// Hermitian conjugate.
    pub fn dagger(&self) -> G16 {
        self.transpose().conj()
    }
    pub fn trace(&self) -> (i64, i64) {
        let mut t = (0, 0);
        for i in 0..N {
            t.0 += self.re[i * N + i];
            t.1 += self.im[i * N + i];
        }
        t
    }
    /// Tr(self b), without forming the product.
    pub fn tr_mul(&self, b: &G16) -> (i64, i64) {
        let mut t = (0, 0);
        for i in 0..N {
            for j in 0..N {
                let (ar, ai) = (self.re[i * N + j], self.im[i * N + j]);
                if ar == 0 && ai == 0 {
                    continue;
                }
                let (br, bi) = (b.re[j * N + i], b.im[j * N + i]);
                t.0 += ar * br - ai * bi;
                t.1 += ar * bi + ai * br;
            }
        }
        t
    }
    pub fn is_zero(&self) -> bool {
        self.re.iter().all(|x| *x == 0) && self.im.iter().all(|x| *x == 0)
    }
    pub fn is_real(&self) -> bool {
        self.im.iter().all(|x| *x == 0)
    }
    pub fn is_hermitian(&self) -> bool {
        *self == self.dagger()
    }
    pub fn is_antisymmetric(&self) -> bool {
        *self == self.transpose().neg()
    }
    /// If the matrix is c times the unit matrix with a real integer c, returns c.
    pub fn as_real_scalar(&self) -> Option<i64> {
        let c = self.re[0];
        if *self == G16::identity().scale(c) {
            Some(c)
        } else {
            None
        }
    }
    pub fn comm(&self, b: &G16) -> G16 {
        self.mul(b).sub(&b.mul(self))
    }
    pub fn anti(&self, b: &G16) -> G16 {
        self.mul(b).add(&b.mul(self))
    }
}

/// The three models (see the head of this file).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Model {
    /// 7+1
    S71,
    /// 4+4, covariant bilinears psi^dagger C^- Theta psi
    S44C,
    /// 4+4, bilinears of the quantized sector psi^dagger beta Theta_eff psi
    S44Q,
}

impl Model {
    /// Prefix of the identifiers of the checks.
    pub fn tag(self) -> &'static str {
        match self {
            Model::S71 => "71s",
            Model::S44C => "44c",
            Model::S44Q => "44q",
        }
    }
    pub fn name(self) -> &'static str {
        match self {
            Model::S71 => "7+1",
            Model::S44C => "4+4 (covariant form)",
            Model::S44Q => "4+4 (quantized-sector form)",
        }
    }
    pub fn all() -> [Model; 3] {
        [Model::S71, Model::S44Q, Model::S44C]
    }
}

/// One of the 256 channels.
#[derive(Clone, Debug)]
pub struct Chan {
    /// bit A is set if the index A belongs to the index set K
    pub mask: u32,
    /// number of indices r
    pub rank: usize,
    /// true if phase_K = i, false if phase_K = 1
    pub phase_i: bool,
    /// eps_K: (Theta^K)^2 = eps_K 1, Theta_K = eps_K Theta^K
    pub eps: i64,
    /// Theta^K
    pub theta: G16,
    /// M_K = Adj Theta^K (Hermitian)
    pub m: G16,
}

/// The matrices of one model.
pub struct Algebra {
    pub model: Model,
    /// the eight matrices Gamma^A from which the channels are built
    pub gen: Vec<G16>,
    /// their squares (+1 or -1)
    pub cliff: [i64; 8],
    /// the adjoint matrix: psibar = psi^dagger adj
    pub adj: G16,
    /// beta: the matrix of the mass term of the single-particle Hamiltonian (Hermitian, square 1)
    pub beta: G16,
    /// 4+4 only: W = i C^- gamma^4 (Hermitian, square 1), the matrix of the covariant charge
    pub w: Option<G16>,
    /// the Hermitian chirality matrix chi with chi^2 = 1 (7+1: i omega1671; 4+4: omega1644)
    pub chi: G16,
    /// the author's real Dirac matrices of the spacetime (for the pair operators)
    pub real_gamma: Vec<G16>,
    /// the real matrix C^- of the pair operators psi^T C^- gamma^J psi
    pub cpair: G16,
    /// the 256 channels; the position in the list is the bit mask of the index set
    pub chan: Vec<Chan>,
}

fn product(list: &[G16], mask: u32) -> G16 {
    let mut m = G16::identity();
    for a in 0..8 {
        if mask & (1 << a) != 0 {
            m = m.mul(&list[a]);
        }
    }
    m
}

impl Algebra {
    pub fn new(gm: &Gammas, model: Model) -> Algebra {
        let g44: Vec<G16> = gm.gamma1644.iter().map(G16::from_imat).collect();
        let g71: Vec<G16> = gm.gamma1671.iter().map(G16::from_imat).collect();
        let (gen, adj, beta, w, real_gamma, cpair) = match model {
            Model::S71 => {
                let om = product(&g71, 255);
                (g71.clone(), g71[4].clone(), g71[4].clone(), None, g71.clone(), g71[4].mul(&om))
            }
            Model::S44C | Model::S44Q => {
                let cm = product(&g44, 0b1111); // C^- = gamma^0 gamma^1 gamma^2 gamma^3
                let beta = g44[4].times_minus_i(); // beta = -i gamma^4
                let w = cm.mul(&g44[4]).times_i(); // W = i C^- gamma^4
                if model == Model::S44C {
                    (g44.clone(), cm.clone(), beta, Some(w), g44.clone(), cm)
                } else {
                    let mut eff: Vec<G16> = Vec::new();
                    for a in 0..8 {
                        eff.push(if a <= 4 { g44[a].times_minus_i() } else { g44[a].clone() });
                    }
                    (eff, beta.clone(), beta, Some(w), g44.clone(), cm)
                }
            }
        };
        let mut cliff = [0i64; 8];
        for a in 0..8 {
            cliff[a] = gen[a].mul(&gen[a]).as_real_scalar().expect("square of a Dirac matrix is not +-1");
        }
        // chirality: the product of the eight REAL matrices, times i if needed to make it Hermitian with square +1
        let om = product(&real_gamma, 255);
        let chi = if om.is_hermitian() && om.mul(&om) == G16::identity() {
            om
        } else {
            let c = om.times_i();
            assert!(c.is_hermitian() && c.mul(&c) == G16::identity(), "no Hermitian chirality matrix");
            c
        };
        let mut chan: Vec<Chan> = Vec::with_capacity(256);
        for mask in 0u32..256 {
            let p = product(&gen, mask);
            let m1 = adj.mul(&p);
            let (theta, m, phase_i) = if m1.is_hermitian() {
                (p, m1, false)
            } else {
                let t = p.times_i();
                let m2 = adj.mul(&t);
                assert!(m2.is_hermitian(), "no phase makes the bilinear of the index set {:#b} real", mask);
                (t, m2, true)
            };
            let eps = theta.mul(&theta).as_real_scalar().expect("square of Theta^K is not +-1");
            assert!(eps == 1 || eps == -1);
            chan.push(Chan { mask, rank: mask.count_ones() as usize, phase_i, eps, theta, m });
        }
        Algebra { model, gen, cliff, adj, beta, w, chi, real_gamma, cpair, chan }
    }

    /// eta_K = product of the squares of the Dirac matrices with index in K.
    pub fn eta_k(&self, mask: u32) -> i64 {
        let mut e = 1;
        for a in 0..8 {
            if mask & (1 << a) != 0 {
                e *= self.cliff[a];
            }
        }
        e
    }

    /// The sign s with Theta^K Theta^L = s Theta^L Theta^K, or None if the two matrices
    /// neither commute nor anticommute.
    pub fn commutation_sign(&self, k: u32, l: u32) -> Option<i64> {
        let a = self.chan[k as usize].theta.mul(&self.chan[l as usize].theta);
        let b = self.chan[l as usize].theta.mul(&self.chan[k as usize].theta);
        if a == b {
            Some(1)
        } else if a == b.neg() {
            Some(-1)
        } else {
            None
        }
    }

    /// 16 F_rs computed from the commutation signs:
    /// 16 F_rs = sum over K of rank r of sign(K, L) for an index set L of rank s.
    /// Returns None if the sum depends on the choice of L within the rank.
    pub fn fierz16(&self) -> Option<[[i64; 9]; 9]> {
        let mut f = [[0i64; 9]; 9];
        let mut seen = [[false; 9]; 9];
        for l in 0u32..256 {
            let s = l.count_ones() as usize;
            let mut row = [0i64; 9];
            for k in 0u32..256 {
                row[k.count_ones() as usize] += self.commutation_sign(k, l)?;
            }
            for r in 0..9 {
                if seen[r][s] {
                    if f[r][s] != row[r] {
                        return None;
                    }
                } else {
                    f[r][s] = row[r];
                    seen[r][s] = true;
                }
            }
        }
        Some(f)
    }

    /// The nine tensors T^(r)_{abcd} = sum_{K of rank r} eps_K (M_K)_{ab} (M_K)_{cd}
    /// (Gaussian integers; index a b c d -> ((a 16 + b) 16 + c) 16 + d).
    /// I_r = sum_{abcd} T^(r)_{abcd} psi_a^* psi_b psi_c^* psi_d.
    pub fn tensors(&self) -> Vec<(Vec<i64>, Vec<i64>)> {
        let mut out: Vec<(Vec<i64>, Vec<i64>)> = (0..9).map(|_| (vec![0i64; N * N * N * N], vec![0i64; N * N * N * N])).collect();
        for ch in &self.chan {
            let nz: Vec<(usize, i64, i64)> = (0..N * N).filter(|&i| ch.m.re[i] != 0 || ch.m.im[i] != 0).map(|i| (i, ch.m.re[i], ch.m.im[i])).collect();
            let t = &mut out[ch.rank];
            for &(i, ar, ai) in &nz {
                for &(j, br, bi) in &nz {
                    t.0[i * N * N + j] += ch.eps * (ar * br - ai * bi);
                    t.1[i * N * N + j] += ch.eps * (ar * bi + ai * br);
                }
            }
        }
        out
    }

    /// 256 times the quadratic forms of the Hartree-Fock energy in the densities:
    /// for n = sum_i x_i d_i / 16,  E_HF = (1/2) sum_r g_r sum_ij Q^(r)_ij x_i x_j  with
    /// 256 Q^(r)_ij = sum_K eps_K [ Tr(M_K d_i) Tr(M_K d_j) - Tr(M_K d_i M_K d_j) ].
    /// Returns None if a value is not real.
    pub fn hf_forms256(&self, dens: &[G16]) -> Option<Vec<Vec<Vec<i64>>>> {
        let n = dens.len();
        let mut out = vec![vec![vec![0i64; n]; n]; 9];
        for ch in &self.chan {
            let t: Vec<(i64, i64)> = dens.iter().map(|d| ch.m.tr_mul(d)).collect();
            let md: Vec<G16> = dens.iter().map(|d| ch.m.mul(d)).collect();
            for i in 0..n {
                for j in 0..n {
                    let direct = (t[i].0 * t[j].0 - t[i].1 * t[j].1, t[i].0 * t[j].1 + t[i].1 * t[j].0);
                    let ex = md[i].tr_mul(&md[j]);
                    if direct.1 - ex.1 != 0 {
                        return None;
                    }
                    out[ch.rank][i][j] += ch.eps * (direct.0 - ex.0);
                }
            }
        }
        Some(out)
    }

    /// 16 times the mean-field potential of rank r for the density matrix n = d/16:
    /// sum_K eps_K [ Tr(M_K d) M_K - M_K d M_K ].
    pub fn mean_field16(&self, r: usize, d: &G16) -> G16 {
        let mut u = G16::zero();
        for ch in self.chan.iter().filter(|c| c.rank == r) {
            let t = ch.m.tr_mul(d);
            // Tr(M d) M
            let mut term = G16::zero();
            for i in 0..N * N {
                term.re[i] = t.0 * ch.m.re[i] - t.1 * ch.m.im[i];
                term.im[i] = t.0 * ch.m.im[i] + t.1 * ch.m.re[i];
            }
            term = term.sub(&ch.m.mul(d).mul(&ch.m));
            u = u.add(&term.scale(ch.eps));
        }
        u
    }

    /// The pairing map of rank r:  P_r(kappa) = sum_K eps_K M_K kappa M_K^T.
    pub fn pair_map(&self, r: usize, kappa: &G16) -> G16 {
        let mut out = G16::zero();
        for ch in self.chan.iter().filter(|c| c.rank == r) {
            out = out.add(&ch.m.mul(kappa).mul(&ch.m.transpose()).scale(ch.eps));
        }
        out
    }

    /// 2 P_+ = 1 + beta: twice the projector on the states of positive energy of a particle at rest.
    pub fn two_p_plus(&self) -> G16 {
        G16::identity().add(&self.beta)
    }

    /// The pair matrix X_J = C^- gamma^{J} (real), J given by its bit mask.
    pub fn pair_matrix(&self, mask: u32) -> G16 {
        self.cpair.mul(&product(&self.real_gamma, mask))
    }
}

