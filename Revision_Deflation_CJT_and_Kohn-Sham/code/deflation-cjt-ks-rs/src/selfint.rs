/// Reduced row-echelon form; returns (matrix, pivot columns).  `prefer` lists the
/// columns that are tried as pivots first, in this order.
pub fn rref(mut m: Vec<Vec<Rat>>, prefer: &[usize]) -> (Vec<Vec<Rat>>, Vec<usize>) {
    let rows = m.len();
    let cols = if rows > 0 { m[0].len() } else { 0 };
    let mut order: Vec<usize> = prefer.to_vec();
    for c in 0..cols {
        if !order.contains(&c) {
            order.push(c);
        }
    }
    let mut pivots: Vec<usize> = Vec::new();
    let mut row = 0;
    for &c in &order {
        if row == rows {
            break;
        }
        let Some(p) = (row..rows).find(|&i| !m[i][c].is_zero()) else { continue };
        m.swap(row, p);
        let inv = m[row][c].recip();
        for j in 0..cols {
            m[row][j] = m[row][j] * inv;
        }
        for i in 0..rows {
            if i != row && !m[i][c].is_zero() {
                let f = m[i][c];
                for j in 0..cols {
                    let x = m[row][j];
                    m[i][j] = m[i][j] - f * x;
                }
            }
        }
        pivots.push(c);
        row += 1;
    }
    (m, pivots)
}

pub fn rank_rat(m: &[Vec<Rat>]) -> usize {
    rref(m.to_vec(), &[]).1.len()
}

/// Binomial coefficient.
pub fn binom(n: i64, k: i64) -> i64 {
    if k < 0 || k > n {
        return 0;
    }
    let mut r = 1i64;
    for i in 0..k {
        r = r * (n - i) / (i + 1);
    }
    r
}

/// The closed form 16 F_rs = sum_l (-1)^{rs - l} C(s, l) C(8 - s, r - l).
pub fn fierz16_closed() -> [[i64; 9]; 9] {
    let mut f = [[0i64; 9]; 9];
    for r in 0..9i64 {
        for s in 0..9i64 {
            let mut x = 0;
            for l in 0..=s.min(r) {
                let sign = if (r * s - l) % 2 == 0 { 1 } else { -1 };
                x += sign * binom(s, l) * binom(8 - s, r - l);
            }
            f[r as usize][s as usize] = x;
        }
    }
    f
}

/// The reduction of the nine invariants to four: I_r = sum_j red[r][j] I_{BASIS4[j]},
/// obtained by solving (1 + F) I = 0 for I_2 .. I_6.
pub const BASIS4: [usize; 4] = [0, 1, 7, 8];

pub fn reduction_matrix() -> [[Rat; 4]; 9] {
    let f = fierz16_closed();
    // rows of (16 + 16 F)
    let m: Vec<Vec<Rat>> = (0..9).map(|r| (0..9).map(|s| Rat::int((f[r][s] + if r == s { 16 } else { 0 }) as i128)).collect()).collect();
    let (red, piv) = rref(m, &[2, 3, 4, 5, 6]);
    assert_eq!(piv, vec![2, 3, 4, 5, 6], "(1 + F) does not have rank 5 with pivots 2..6");
    let mut out = [[Rat::ZERO; 4]; 9];
    for (j, &b) in BASIS4.iter().enumerate() {
        out[b][j] = Rat::ONE;
    }
    for (row, &p) in piv.iter().enumerate() {
        // I_p + sum_{b in basis} red[row][b] I_b = 0
        for (j, &b) in BASIS4.iter().enumerate() {
            out[p][j] = -red[row][b];
        }
    }
    out
}

/// The four effective couplings (g_0eff, g_1eff, g_7eff, g_8eff) of nine couplings.
pub fn reduce_couplings(g: &[f64; 9]) -> [f64; 4] {
    let red = reduction_matrix();
    let mut out = [0.0; 4];
    for r in 0..9 {
        for j in 0..4 {
            out[j] += g[r] * red[r][j].to_f64();
        }
    }
    out
}

