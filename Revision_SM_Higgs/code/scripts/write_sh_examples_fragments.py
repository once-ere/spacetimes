#!/usr/bin/env python3
"""
write_sh_examples_fragments.py (Revision_SM_Higgs) -- the machine-written fragments of the explicit examples (object
O21 of the task record): the verdicts of the three programs that compute and check them.

No manuscript prints the examples yet: the author stopped the writing of manuscripts on 22 November 2026 (entry C27 of
the task record), so this script writes only what the task record and the README state.

Reads data/hck_sh_examples_checks.txt (Rust, sh_examples), data/hck_sh_examples_checks_python.txt
(python/sh_examples.py) and data/hck_sh_examples_checks_wolfram.txt (wolfram/source/sh_examples.wls), and writes
provenance/generated/sh_examples.md with the fragments ex_verdict_rust, ex_verdict_python, ex_verdict_wolfram.
Usage (from the folder Revision_SM_Higgs):   python3 code/scripts/write_sh_examples_fragments.py
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
D = os.path.join(ROOT, "data")


def verdict(name):
    """the line 'VERDICT: ...' of a report"""
    text = open(os.path.join(D, name), encoding="utf-8").read()
    mt = re.search(r"^VERDICT: (.*)$", text, re.M)
    if not mt:
        sys.exit("no verdict in data/" + name)
    return mt.group(1)


def main():
    fr = {
        "ex_verdict_rust": verdict("hck_sh_examples_checks.txt"),
        "ex_verdict_python": verdict("hck_sh_examples_checks_python.txt"),
        "ex_verdict_wolfram": verdict("hck_sh_examples_checks_wolfram.txt"),
    }
    out = ["<!-- generated by code/scripts/write_sh_examples_fragments.py from data/hck_sh_examples_checks*.txt; do not edit -->"]
    for k in sorted(fr):
        out += ["<!-- BEGIN %s -->" % k, fr[k], "<!-- END %s -->" % k]
    path = os.path.join(ROOT, "provenance", "generated", "sh_examples.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("[ex] wrote %s (%d fragments)" % (os.path.relpath(path, ROOT), len(fr)))
    for k in sorted(fr):
        print("  %-20s %s" % (k, fr[k]))


if __name__ == "__main__":
    main()
