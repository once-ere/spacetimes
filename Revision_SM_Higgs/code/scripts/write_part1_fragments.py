#!/usr/bin/env python3
"""
write_part1_fragments.py (Revision_SM_Higgs) -- the machine-written fragments of part I of superfluid.md.

Reads the reports and the values written by the programs of part I
    data/hck_part1_checks.txt          (Rust program sf_part1)
    data/hck_part1_checks_python.txt   (Python program python/sf_part1.py)
    data/part1_values.csv              (Rust program sf_part1)
and writes provenance/generated/part1.md with the fragments
    p1_checks_rust, p1_checks_python   the tables of the checks (identifier, result, deviation, tolerance, statement)
    p1_verdict_rust, p1_verdict_python the verdict lines
    p1_<name>                          each named value, with 10 significant digits (in a formula: {{GENM:p1_<name>}})
Usage (from the folder Revision_SM_Higgs):   python3 code/scripts/write_part1_fragments.py
"""
import csv
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def esc(s):
    """escape a plain-text statement of a check for a Markdown table (no LaTeX inside the statements)"""
    s = s.replace("|", "/").replace("_", "\\_").replace("*", "\\*").replace("^", "\\^").replace("<", "&lt;")
    s = s.replace("$", "\\$")
    return s


def table(path):
    rows = []
    verdict = ""
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = re.match(r"(PASS|FAIL) (\S+)\s+deviation (\S+) \(tolerance (\S+)\): (.*)$", line)
        if m:
            rows.append((m.group(2), m.group(1), m.group(3), m.group(4), m.group(5)))
            continue
        m = re.match(r"(PASS|FAIL) (\S+)\s+(.*) \[(.*)\]$", line)
        if m:
            rows.append((m.group(2), m.group(1), "--", "--", m.group(3) + " (" + m.group(4) + ")"))
            continue
        if line.startswith("VERDICT"):
            verdict = line
    out = ["| check | result | deviation | tolerance | statement |", "|:---|:---|:---|:---|:---|"]
    for r in rows:
        out.append("| %s | %s | %s | %s | %s |" % (r[0], r[1], r[2], r[3], esc(r[4])))
    return "\n".join(out), verdict


def fmt(v):
    x = float(v)
    if x == int(x) and abs(x) < 1e6:
        return "%d" % int(x)
    s = "%.10g" % x
    if "e" in s:
        mant, ex = s.split("e")
        return "%s\\times10^{%d}" % (mant, int(ex))
    return s


def main():
    frags = {}
    t, v = table(os.path.join(ROOT, "data", "hck_part1_checks.txt"))
    frags["p1_checks_rust"] = t
    frags["p1_verdict_rust"] = v
    t, v = table(os.path.join(ROOT, "data", "hck_part1_checks_python.txt"))
    frags["p1_checks_python"] = t
    frags["p1_verdict_python"] = v
    with open(os.path.join(ROOT, "data", "part1_values.csv")) as f:
        r = csv.reader(f)
        next(r)
        for name, val in r:
            frags["p1_" + name.replace(".", "")] = "$" + fmt(val) + "$"
    out = ["<!-- Generated by code/scripts/write_part1_fragments.py; do not edit. -->"]
    for k, v in frags.items():
        out.append("<!-- BEGIN %s -->\n%s\n<!-- END %s -->" % (k, v, k))
    os.makedirs(os.path.join(ROOT, "provenance", "generated"), exist_ok=True)
    with open(os.path.join(ROOT, "provenance", "generated", "part1.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote provenance/generated/part1.md with %d fragments" % len(frags))


if __name__ == "__main__":
    main()
