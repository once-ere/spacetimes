#!/usr/bin/env python3
"""
write_lg_curved_fragments.py (Revision_Lord_Gravity) -- the machine-written fragments of Part III of lord_gravity.md:
the verdicts of the three programs that check the gravitational coupling of the brochon (the Rust program lg_curved,
the Python program python/lg_curved.py and the Wolfram script wolfram/source/lg_curved.wls), and the numbers that the
text quotes from them, read from data/lg_curved_values.csv (written by lg_curved).

Every number that the manuscript states about these checks is written here from the reports, so that the text and the
reports cannot differ.  The program stops if a report is missing, has no verdict line, or does not pass completely, and
if a finding about a printed coefficient is not the stated factor.

Usage (from the folder Revision_Lord_Gravity):   python3 code/scripts/write_lg_curved_fragments.py
Output: provenance/generated/lg_curved.md
"""
import csv
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "provenance", "generated", "lg_curved.md")


def verdict(name):
    """the verdict line of a report, as 'ALL PASS (n of n)'; stops unless all checks passed"""
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        sys.exit("%s: missing" % name)
    text = open(path, encoding="utf-8").read()
    m = re.search(r"VERDICT: (ALL PASS \((\d+) of (\d+)\))", text)
    if not m:
        sys.exit("%s: no passing verdict line" % name)
    if m.group(2) != m.group(3):
        sys.exit("%s: not all checks passed" % name)
    nlines = len(re.findall(r"^(PASS|FAIL) ", text, re.M))
    if nlines != int(m.group(3)):
        sys.exit("%s: %d check lines but the verdict counts %s" % (name, nlines, m.group(3)))
    return m.group(1), int(m.group(3))


def value(rows, q):
    for r in rows:
        if r["quantity"] == q:
            return float(r["value"])
    sys.exit("lg_curved_values.csv: no row for '%s'" % q)


def sci(x, digits=2):
    """a number in the notation of the manuscript: 0.139 or 2.76, or a x 10^n for small and large numbers"""
    if 1e-2 <= abs(x) < 1e3:
        return "$%s$" % ("%.*g" % (digits + 1, x))
    m, e = ("%.*e" % (digits, x)).split("e")
    return "$%s\\times10^{%d}$" % (m, int(e))


def main():
    frags = {}
    for key, name in (("lgc_verdict_rust", "hck_lg_curved_checks.txt"),
                      ("lgc_verdict_python", "hck_lg_curved_checks_python.txt"),
                      ("lgc_verdict_wolfram", "hck_lg_curved_checks_wolfram.txt")):
        v, n = verdict(name)
        frags[key] = v
        frags[key.replace("verdict", "n")] = str(n)
    rows = list(csv.DictReader(open(os.path.join(DATA, "lg_curved_values.csv"), encoding="utf-8")))
    frags["lgc_r_min"] = sci(value(rows, "random tetrads: smallest |R|"))
    frags["lgc_r_max"] = sci(value(rows, "random tetrads: largest |R|"))
    frags["lgc_rc_min"] = sci(value(rows, "conformally flat: smallest |R|"))
    frags["lgc_rc_max"] = sci(value(rows, "conformally flat: largest |R|"))
    for key, q in (("lgc_g8b", "G-8b printed 1/2: relative deviation"),
                   ("lgc_g10b", "G-10b printed 1/2: relative deviation")):
        v = value(rows, q)
        if abs(v - 1.0) > 1e-6:
            sys.exit("%s: the printed coefficient is not exactly twice (%.12f)" % (q, v))
        frags[key] = "$%.6f$" % v
    egap = value(rows, "E_gap of the CJT ground state")
    frags["lgc_egap"] = "$%.10f$" % egap
    frags["lgc_g17b"] = sci(value(rows, "G-17b smallest deviation with W^1 and B"))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("<!-- generated by code/scripts/write_lg_curved_fragments.py from the reports of lg_curved; do not edit -->\n")
        for k in sorted(frags):
            f.write("<!-- BEGIN %s -->\n%s\n<!-- END %s -->\n" % (k, frags[k], k))
    print("wrote %s (%d fragments)" % (os.path.relpath(OUT, ROOT), len(frags)))


if __name__ == "__main__":
    main()
