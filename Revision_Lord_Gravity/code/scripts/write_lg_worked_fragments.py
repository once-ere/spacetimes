#!/usr/bin/env python3
r"""
write_lg_worked_fragments.py (Revision_Lord_Gravity) -- the fragments of the worked examples of the manuscript
lord_gravity: the values that the Rust program lg_worked (crate rust/lgworked) computed and wrote into
data/lg_worked_values.csv, as formulas for the manuscript, and the verdicts of the three programs that check them
(data/hck_lg_worked_checks.txt of Rust, hck_lg_worked_checks_python.txt of python/lg_worked.py and
hck_lg_worked_checks_wolfram.txt of wolfram/source/lg_worked.wls).

Every row "name,value" of the data file becomes the fragment lgw_<name> (the name in lower case, with every character
that is not a letter or a digit replaced by "_"), with the value written in LaTeX for use inside a formula:
  * an exact value "p/q" as \tfrac{p}{q}, a complex one "a + b i" as a + b i, a unit "e0" as \mathbf e_{0};
  * a list "(a, b, ...)" as the row (a,b,...); a list of lists "((a, b), (c, d))" as a pmatrix;
  * a floating-point number (17 digits in the data file) with ten significant digits.
The converters ex_atom, ex_scalar, ex_split and ex_tex are copied from paper_prd/scripts/build_paper.py of the folder
Revision_SM_Higgs, with the macros of that folder (\e, \LL) replaced by their expansions.  A row whose value the
converter does not know stops the script.

Usage (from the folder Revision_Lord_Gravity):   python3 code/scripts/write_lg_worked_fragments.py
"""
import csv
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "data")


def ex_atom(tok):
    """one token of a value as LaTeX (math mode)"""
    m = re.fullmatch(r"(-?)(\d+)/(\d+)", tok)
    if m:
        return "%s\\tfrac{%s}{%s}" % (m.group(1), m.group(2), m.group(3))
    m = re.fullmatch(r"(-?)e([0-7])", tok)
    if m:
        return "%s\\mathbf e_{%s}" % (m.group(1), m.group(2))
    if tok in ("i", "-i", "+", "-", "="):
        return tok
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)(?:e([-+]?\d+))?", tok)
    if m:
        return m.group(1) + ("\\times10^{%d}" % int(m.group(2)) if m.group(2) else "")
    sys.exit("ex_atom: a token of a worked example that the converter does not know: %r" % tok)


def ex_scalar(s):
    """a scalar value (a sum of terms separated by blanks) as LaTeX"""
    return "".join(ex_atom(t) for t in s.split())


def ex_split(s):
    """the top-level items of a parenthesized list "(a, b, ...)" """
    if not (s.startswith("(") and s.endswith(")")):
        sys.exit("ex_split: not a parenthesized list: %r" % s)
    items, depth, cur = [], 0, ""
    for ch in s[1:-1]:
        if ch == "," and depth == 0:
            items.append(cur.strip())
            cur = ""
            continue
        depth += (ch == "(") - (ch == ")")
        cur += ch
    items.append(cur.strip())
    return items


def ex_tex(v):
    """a value as LaTeX for math mode: a list of lists as a pmatrix, a list as a row (a1,a2,...), else ex_scalar"""
    v = v.strip()
    if v.startswith("("):
        items = ex_split(v)
        if all(x.startswith("(") for x in items):
            body = "\\\\".join("&".join(ex_scalar(y) for y in ex_split(x)) for x in items)
            return "\\begin{pmatrix}%s\\end{pmatrix}" % body
        return "(" + ",".join(ex_scalar(x) for x in items) + ")"
    return ex_scalar(v)


def value_tex(v):
    """the LaTeX of a value of the data file: a floating-point number with ten significant digits, else ex_tex"""
    if re.fullmatch(r"-?\d\.\d{17}e-?\d+", v.strip()):
        x = float(v)
        s = "%.10g" % x
        if "e" in s:
            mant, ex = s.split("e")
            return "%s\\times10^{%d}" % (mant, int(ex))
        return s
    return ex_tex(v)


def verdict(name):
    """the verdict line of a report"""
    path = os.path.join(DATA, name)
    lines = [ln.strip() for ln in open(path, encoding="utf-8") if ln.startswith("VERDICT")]
    if not lines:
        sys.exit("write_lg_worked_fragments: no verdict in %s" % name)
    return lines[-1]


def main():
    fr = {}
    with open(os.path.join(DATA, "lg_worked_values.csv"), newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            key = "lgw_" + re.sub(r"[^a-z0-9]+", "_", row["name"].lower())
            if key in fr:
                sys.exit("write_lg_worked_fragments: two rows give the key %s" % key)
            fr[key] = "$" + value_tex(row["value"]) + "$"
    fr["lgw_verdict_rust"] = verdict("hck_lg_worked_checks.txt")
    fr["lgw_verdict_python"] = verdict("hck_lg_worked_checks_python.txt")
    fr["lgw_verdict_wolfram"] = verdict("hck_lg_worked_checks_wolfram.txt")
    out = ["<!-- generated by code/scripts/write_lg_worked_fragments.py from data/lg_worked_values.csv and the reports "
           "data/hck_lg_worked_checks*.txt; do not edit -->"]
    for k in sorted(fr):
        out += ["<!-- BEGIN %s -->" % k, fr[k], "<!-- END %s -->" % k]
    path = os.path.join(ROOT, "provenance", "generated", "lg_worked.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("[lgw] wrote %s (%d fragments)" % (os.path.relpath(path, ROOT), len(fr)))


if __name__ == "__main__":
    main()
