#!/usr/bin/env python3
"""
write_lg_lord_fragments.py (Revision_Lord_Gravity) -- the machine-written fragments of Parts I and II of lord_gravity.md:
the verdicts of the three programs that check Lord's equations and their association with the project (the Rust
program lg_lord, the Python program python/lg_lord.py and the Wolfram script wolfram/source/lg_lord.wls), and the
numbers of the findings about Lord's equations as printed, read from data/lg_lord_findings.csv.

Every number that the manuscript states about these checks is written here from the reports, so that the text and the
reports cannot differ.  The program stops if a report is missing, has no verdict line, or does not pass completely.

Usage (from the folder Revision_Lord_Gravity):   python3 code/scripts/write_lg_lord_fragments.py
Output: provenance/generated/lg_lord.md
"""
import csv
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "provenance", "generated", "lg_lord.md")


def verdict(name):
    """the verdict line of a report, as 'ALL PASS (n of n)'; stops unless all checks passed"""
    text = open(os.path.join(DATA, name), encoding="utf-8").read()
    m = re.search(r"VERDICT: (ALL PASS \((\d+) of (\d+)\))", text)
    if not m:
        sys.exit("%s: no passing verdict line" % name)
    if m.group(2) != m.group(3):
        sys.exit("%s: not all checks passed" % name)
    nlines = len(re.findall(r"^(PASS|FAIL) ", text, re.M))
    if nlines != int(m.group(3)):
        sys.exit("%s: %d check lines but the verdict counts %s" % (name, nlines, m.group(3)))
    return m.group(1), int(m.group(3))


def finding(rows, cid):
    for r in rows:
        if r["check"] == cid:
            return float(r["value"])
    sys.exit("lg_lord_findings.csv: no row for %s" % cid)


def main():
    frags = {}
    for key, name in (("lgl_verdict_rust", "hck_lg_lord_checks.txt"),
                      ("lgl_verdict_python", "hck_lg_lord_checks_python.txt"),
                      ("lgl_verdict_wolfram", "hck_lg_lord_checks_wolfram.txt")):
        v, n = verdict(name)
        frags[key] = v
        frags[key.replace("verdict", "n")] = str(n)
    rows = list(csv.DictReader(open(os.path.join(DATA, "lg_lord_findings.csv"), encoding="utf-8")))
    # the numbers of the findings, rounded for the text (the reports keep all digits)
    frags["lgl_l114_dev"] = "$%.2f$" % finding(rows, "L1-14")
    frags["lgl_l43_rel"] = "$%.2f$" % finding(rows, "L4-3")
    v45 = finding(rows, "L4-5")
    if abs(v45 - 2.0) > 1e-6:
        sys.exit("L4-5: the printed law is not exactly the opposite sign (%.12f)" % v45)
    frags["lgl_l45_ratio"] = "$%.6f$" % v45
    frags["lgl_l46d_rel"] = "$%.2f$" % finding(rows, "L4-6d")
    v410c = finding(rows, "L4-10c")
    if abs(v410c - 1.0) > 1e-6:
        sys.exit("L4-10c: the printed coefficient is not exactly twice (%.12f)" % v410c)
    frags["lgl_l410c_rel"] = "$%.6f$" % v410c
    frags["lgl_l410d_ratio"] = "$%.1f$" % finding(rows, "L4-10d")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("<!-- generated by code/scripts/write_lg_lord_fragments.py from the reports of lg_lord; do not edit -->\n")
        for k in sorted(frags):
            f.write("<!-- BEGIN %s -->\n%s\n<!-- END %s -->\n" % (k, frags[k], k))
    print("wrote %s (%d fragments)" % (os.path.relpath(OUT, ROOT), len(frags)))


if __name__ == "__main__":
    main()
