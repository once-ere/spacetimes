#!/usr/bin/env python3
"""
write_lg_annih_fragments.py (Revision_Lord_Gravity) -- the machine-written fragments of stage 7d of task C23 (the
quasi-particles of the superfluid as the particles and antiparticles of a Dirac field of the mass of the gap, the conserved
quasi-particle number, and the annihilation of the pair): the verdicts of the three programs that compute and check it (the
Rust program lg_annih, the Python program python/lg_annih.py and the Wolfram script wolfram/source/lg_annih.wls), and the
numbers that the task record and the manuscript quote, read from the data files that lg_annih writes
(data/lg_annih_values.csv, data/lg_annih_scan.csv).

The program stops if a report is missing, has no verdict line, or does not pass completely, and if a quantity is missing.

Usage (from the folder Revision_Lord_Gravity):   python3 code/scripts/write_lg_annih_fragments.py
Output: provenance/generated/lg_annih.md
"""
import csv
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "provenance", "generated", "lg_annih.md")


def verdict(name):
    """the verdict line of a report, as 'ALL PASS (n of n)'; stops unless all checks passed"""
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        sys.exit("%s: missing" % name)
    text = open(path, encoding="utf-8").read()
    m = re.search(r"VERDICT: (ALL PASS \((\d+) of (\d+)\))", text)
    if not m or m.group(2) != m.group(3):
        sys.exit("%s: no passing verdict line" % name)
    if len(re.findall(r"^(PASS|FAIL) ", text, re.M)) != int(m.group(3)):
        sys.exit("%s: the number of check lines differs from the verdict" % name)
    return m.group(1), int(m.group(3)), text


def deviation(text, cid, name):
    m = re.search(r"^PASS %s\s+deviation ([0-9.e+-]+)" % re.escape(cid), text, re.M)
    if not m:
        sys.exit("%s: no deviation for %s" % (name, cid))
    return float(m.group(1))


def sci(x, digits=2):
    """0.139 or 2.76, or a x 10^n for small and large numbers"""
    if 1e-2 <= abs(x) < 1e3:
        return "%s" % ("%.*g" % (digits + 1, x))
    m, e = ("%.*e" % (digits, x)).split("e")
    return "%s\\times10^{%d}" % (m, int(e))


def main():
    frags = {}
    texts = {}
    for key, name in (("lga_verdict_rust", "hck_lg_annih_checks.txt"),
                      ("lga_verdict_python", "hck_lg_annih_checks_python.txt"),
                      ("lga_verdict_wolfram", "hck_lg_annih_checks_wolfram.txt")):
        v, n, text = verdict(name)
        frags[key] = v
        frags[key.replace("verdict", "n")] = str(n)
        texts[key] = text
    path = os.path.join(DATA, "lg_annih_values.csv")
    if not os.path.exists(path):
        sys.exit("lg_annih_values.csv: missing")
    vals = {r["name"]: float(r["value"]) for r in csv.DictReader(open(path, encoding="utf-8"))}
    need = ("decay_one_kind_2zeugons", "decay_one_kind_3zeugons", "decay_even_singlet", "decay_odd_triplet",
            "hfs_two_particles", "hfs_odd_triplet", "lifetime_even_singlet_s_Lambda_1GeV", "lifetime_odd_triplet_s_Lambda_1GeV",
            "lifetime_even_singlet_s_Lambda_1eV", "lifetime_odd_triplet_s_Lambda_1eV", "lifetime_even_singlet_s_Lambda_1TeV",
            "lifetime_odd_triplet_s_Lambda_1TeV")
    for q in need:
        if q not in vals:
            sys.exit("lg_annih_values.csv: no row for %s" % q)
    frags["lga_g2_one"] = "$%s$" % sci(vals["decay_one_kind_2zeugons"], 3)
    frags["lga_g3_one"] = "$%s$" % sci(vals["decay_one_kind_3zeugons"], 3)
    frags["lga_g2_even"] = "$%s$" % sci(vals["decay_even_singlet"], 3)
    frags["lga_g3_odd"] = "$%s$" % sci(vals["decay_odd_triplet"], 3)
    frags["lga_hfs_pp"] = "$%s$" % sci(vals["hfs_two_particles"], 3)
    frags["lga_hfs_odd"] = "$%s$" % sci(vals["hfs_odd_triplet"], 3)
    for tag in ("1eV", "1GeV", "1TeV"):
        frags["lga_tau2_%s" % tag] = "$%s$" % sci(vals["lifetime_even_singlet_s_Lambda_%s" % tag], 1)
        frags["lga_tau3_%s" % tag] = "$%s$" % sci(vals["lifetime_odd_triplet_s_Lambda_%s" % tag], 1)
    frags["lga_dev_an2"] = "$%s$" % sci(deviation(texts["lga_verdict_rust"], "AN-2", "rust"), 1)
    frags["lga_dev_an3b"] = "$%s$" % sci(deviation(texts["lga_verdict_rust"], "AN-3b", "rust"), 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("<!-- generated by code/scripts/write_lg_annih_fragments.py from the data and reports of lg_annih; do not edit -->\n")
        for k in sorted(frags):
            f.write("<!-- BEGIN %s -->\n%s\n<!-- END %s -->\n" % (k, frags[k], k))
    print("wrote %s (%d fragments)" % (os.path.relpath(OUT, ROOT), len(frags)))


if __name__ == "__main__":
    main()
