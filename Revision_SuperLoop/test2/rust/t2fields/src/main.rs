fn sci(x: f64) -> String {
    format!("{:.1e}", x)
}

// ------------------------------------------------------------------ helpers

fn rnd_c(rng: &mut Rng) -> C64 {
    c(rng.unit(), rng.unit())
}

fn rnd_vec(rng: &mut Rng, n: usize) -> Vec<C64> {
    (0..n).map(|_| rnd_c(rng)).collect()
}

fn vnorm(v: &[C64]) -> f64 {
    v.iter().map(|z| z.norm_sqr()).sum::<f64>().sqrt()
}

fn vsub(a: &[C64], b: &[C64]) -> Vec<C64> {
    a.iter().zip(b).map(|(x, y)| *x - *y).collect()
}

/// the 4 x 4 Lorentz generator of the imaginary bi-quaternion sum_j (om_j J^j + vp_j K^j)
fn lorentz_elem(om: &[f64; 3], vp: &[f64; 3]) -> [C64; 4] {
    let mut x = [C64::ZERO; 4];
    for j in 0..3 {
        x[j + 1] = c(0.5 * om[j], 0.5 * vp[j]);
    }
    x
}

/// the 8 x 8 gauge matrix gv A^iota T^iota + gF A^F (isospin part only, Dirac identity)
fn gauge8(gv: f64, gf: f64, a: &[f64; 3], af: f64) -> CMat {
    let mut m = CMat::identity(8).scale_r(gf * af);
    for i in 0..3 {
        m = m.add(&tiso(i + 1).scale_r(gv * a[i]));
    }
    m
}

/// Split long aligned displays into one display per equation, so that the PDF can break pages between the
/// equations: every block "$$\begin{aligned} ... \end{aligned}$$" whose equations are separated by "\\[2pt]"
/// becomes one such block per equation (the line breaks inside an equation are kept).
fn split_displays(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(a) = rest.find("$$\\begin{aligned}") {
        out.push_str(&rest[..a]);
        let after = &rest[a + "$$\\begin{aligned}".len()..];
        let b = after.find("\\end{aligned}$$").expect("an aligned display ends");
        let inner = &after[..b];
        let eqs: Vec<&str> = inner.split("\\\\[2pt]").collect();
        for (i, e) in eqs.iter().enumerate() {
            let e = e.trim();
            if e.is_empty() {
                continue;
            }
            if i > 0 {
                out.push_str("\n\n");
            }
            out.push_str(&format!("$$\\begin{{aligned}}\n{}\n\\end{{aligned}}$$", e));
        }
        rest = &after[b + "\\end{aligned}$$".len()..];
    }
    out.push_str(rest);
    out
}

