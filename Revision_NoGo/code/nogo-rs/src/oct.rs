//! Command `octonions`: the octonions O_NG and the split octonions Os_NG, built by
//! the Cayley-Dickson construction from the quaternions H, and every algebraic
//! fact about them that the analysis of the no-go theorems uses.
//!
//! Cayley-Dickson doubling.  An element of the doubled algebra is a pair (a, b) of
//! quaternions, written a + b l_NG, with the product
//!
//!     (a, b) (c, d) = (a c + g conj(d) b ,  d a + b conj(c)),                (CD)
//!
//! where conj is quaternion conjugation and g = -1 gives the octonions O_NG
//! (l_NG^2 = -1), g = +1 the split octonions Os_NG (l_NG^2 = +1).  Basis:
//!
//!     e0 = 1, e1 = i, e2 = j, e3 = k, e4 = l, e5 = i l, e6 = j l, e7 = k l,
//!
//! i.e. e_p = (unit quaternion p, 0) for p = 0..3 and e_{4+p} = (0, unit quaternion p).
//! The norm N(x) = x conj(x) is diagonal in this basis:
//!     O_NG : N = diag(+1, +1, +1, +1, +1, +1, +1, +1)        (Euclidean, 8+0)
//!     Os_NG: N = diag(+1, +1, +1, +1, -1, -1, -1, -1)        (split, 4+4)
//!
//! Checks (numbered O-1 ... O-15 in the report data/ng_octonions_checks.txt):
//! unit, norm, composition N(xy) = N(x)N(y), alternativity, non-associativity,
//! the Moufang identities, the Jacobiator of the commutator equals six times the
//! associator, the Jacobiators span the imaginary octonions (so the commutator
//! algebra of Im O is a Malcev algebra with NO nonzero linear representation),
//! the Malcev identity, the derivation algebras (dimension 14; the compact G2 and
//! the split G2, told apart by the signature of their Killing forms), the Lie
//! algebra generated by the left multiplications (so(8) and so(4,4)), the
//! quaternionic Z2 grading O = H + H l, the octonionic Clifford representations
//! of the 7+1 and 4+4 Dirac algebras, and their equivalence with the project
//! matrices gamma1671[A], gamma1644[A] (explicit invertible intertwiners).

